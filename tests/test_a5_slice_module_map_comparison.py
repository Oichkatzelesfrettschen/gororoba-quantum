def test_the_cells_are_the_header_files_of_the_module_map_rows() -> None:
    mod = load()
    if [(orbit, prime, root) for orbit, _tag, prime, root, _header in mod.CELLS] != [
        ("N-", 32009, 10754),
        ("N-", 32029, 9115),
        ("N-", 32057, 8059),
        ("N+", 32009, 10754),
        ("N+", 32029, 9115),
    ]:
        raise AssertionError(mod.CELLS)
    for _orbit, _tag, prime, root, header in mod.CELLS:
        if pow(root, 2, prime) != prime - 1 or not (mod.FIBERS / header).is_file():
            raise AssertionError(header)


def test_an_error_line_or_a_missing_end_raises() -> None:
    mod = load()
    with pytest.raises(RuntimeError):
        mod.parse("RESULT scalar 1 1 -1\n   ? error\nRESULT done 1\n")
    with pytest.raises(RuntimeError):
        mod.parse("RESULT scalar 1 1 -1\n")
    row = mod.parse("RESULT scalar 1 1 -1\nRESULT weight_image y(8) y(3)\nRESULT done 1\n")
    if row["scalar"] != [1, 1, -1] or row["weight_image"] != [["y(8)", "y(3)"]]:
        raise AssertionError(row)


