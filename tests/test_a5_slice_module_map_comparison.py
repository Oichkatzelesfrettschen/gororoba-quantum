"""The check of the slice comparison of the E8-bar module maps, on a fixture built from the module's tables.

The retained record replays on demand through the gate core-a5-slice-module-map-comparison of ci/gates.json.
"""

import importlib.util
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "docs/evidence/a5-kernel-attachments/slice_module_map_comparison.py"


def load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("a5_slice_module_map_comparison", SCRIPT)
    if spec is None or spec.loader is None:
        raise ImportError(SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def fixture(mod: ModuleType, family: str = "e8") -> list[dict[str, Any]]:
    cells = []
    for item in mod.FAMILIES[family]:
        row = mod.expected(item)
        _orbit, tag, prime, root, _header = item
        row["weight_image"] = [list(pair) for pair in row["weight_image"]]
        row["header_image"] = [list(pair) for pair in row["header_image"]]
        row |= {"scalar": [1, 1, mod.scalar(tag, prime, root)], "control_indices": [3, 13, 15]}
        row |= {control: [1, 0, 0] for control in mod.CONTROLS}
        cells.append(row)
    return cells


def test_the_fixture_passes_and_holds_five_cells() -> None:
    mod = load()
    cells = fixture(mod)
    if len(cells) != 5 or mod.problems(cells):
        raise AssertionError(mod.problems(cells))


