"""The check of the slice comparison of the E8-bar module maps, on a fixture built from the module's tables.

The retained record replays on demand through the gate core-a5-slice-module-map-comparison of ci/gates.json.
"""

import importlib.util
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "docs/evidence/a5-kernel-attachments/slice_module_map_comparison.py"


def load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("a5_slice_module_map_comparison", SCRIPT)
    if spec is None or spec.loader is None:
        raise ImportError(SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def fixture(mod: ModuleType) -> list[dict[str, Any]]:
    cells = []
    for item in mod.CELLS:
        row = mod.expected(item)
        _orbit, _tag, prime, root, _header = item
        row["weight_image"] = [list(pair) for pair in row["weight_image"]]
        row["header_image"] = [list(pair) for pair in row["header_image"]]
        row |= {"scalar": [1, 1, root * pow(2, -1, prime) % prime], "control_indices": [3, 13, 15]}
        row |= {control: [1, 0, 0] for control in mod.CONTROLS}
        cells.append(row)
    return cells


def test_the_fixture_passes_and_holds_five_cells() -> None:
    mod = load()
    cells = fixture(mod)
    if len(cells) != 5 or mod.problems(cells):
        raise AssertionError(mod.problems(cells))


MUTATIONS = {
    "maps related by no scalar": lambda cells: cells[0].update(scalar=[1, 0, 0]),
    "another scalar": lambda cells: cells[1].update(scalar=[1, 1, -1]),
    "the scalar of another prime": lambda cells: cells[1].update(scalar=[1, 1, 5377]),
    "a singular map of the coordinates of B": lambda cells: cells[2].update(scalar=[0, 1, 20058]),
    "exchanged images accepted": lambda cells: cells[0].update(control_images_exchanged=[1, 1, -1]),
    "a perturbed slice map accepted": lambda cells: cells[3].update(control_map_perturbed=[1, 1, -1]),
    "exchanged header coordinates accepted": lambda cells: cells[4].update(control_generators_exchanged=[1, 1, 5]),
    "a control on no generator": lambda cells: cells[0].update(control_indices=[0, 13, 15]),
    "a control exchanging one coordinate with itself": lambda cells: cells[0].update(control_indices=[3, 13, 13]),
    "a transported ideal that differs from the header ideal": lambda cells: cells[1].update(transported=[0, 3]),
    "a slice map that moves the linear forms of the colon ideal": lambda cells: cells[2].update(linear_parts=[1, 0]),
    "a two-dimensional solution space on the weight slice": lambda cells: cells[3].update(weight_solutions=[2]),
    "a header control system with a solution": lambda cells: cells[4].update(header_control_solutions=[1]),
    "a singular header map": lambda cells: cells[0].update(header_det_nonzero=[0]),
    "a radical not generated by its linear forms": lambda cells: cells[1].update(weight_side=[5, 0, 5, 16, 1]),
    "another header relation file": lambda cells: cells[3].update(header="working/runs/other.rel"),
    "another root": lambda cells: cells[2].update(root=24998),
    "four images": lambda cells: cells[0]["weight_image"].pop(),
    "a header map in another normalization": lambda cells: cells[0]["header_image"][4].__setitem__(1, "-5377*y(4)"),
    "a weight-slice map with the other sign of i": lambda cells: cells[3]["weight_image"][4].__setitem__(
        1, "-2*y(12)-10754*y(13)-10754*y(17)"
    ),
    "a cell removed": lambda cells: cells.pop(),
    "an extra field": lambda cells: cells[0].update(note="x"),
}


@pytest.mark.parametrize("name", sorted(MUTATIONS))
def test_a_changed_record_is_reported(name: str) -> None:
    mod = load()
    cells = fixture(mod)
    MUTATIONS[name](cells)
    if not mod.problems(cells):
        raise AssertionError(f"{name}: the changed record passes")


def test_the_cells_are_the_header_files_of_the_module_map_rows() -> None:
    mod = load()
    if [(orbit, prime, root) for orbit, _tag, prime, root, _header in mod.CELLS] != [
        ("N-", 32009, 10754),
        ("N-", 32029, 9115),
        ("N-", 32057, 8059),
        ("N+", 32009, 10754),
        ("N+", 32029, 9115),
    ]:
        raise AssertionError(mod.CELLS)
    for _orbit, _tag, prime, root, header in mod.CELLS:
        if pow(root, 2, prime) != prime - 1 or not (mod.FIBERS / header).is_file():
            raise AssertionError(header)


def test_an_error_line_or_a_missing_end_raises() -> None:
    mod = load()
    with pytest.raises(RuntimeError):
        mod.parse("RESULT scalar 1 1 -1\n   ? error\nRESULT done 1\n")
    with pytest.raises(RuntimeError):
        mod.parse("RESULT scalar 1 1 -1\n")
    row = mod.parse("RESULT scalar 1 1 -1\nRESULT weight_image y(8) y(3)\nRESULT done 1\n")
    if row["scalar"] != [1, 1, -1] or row["weight_image"] != [["y(8)", "y(3)"]]:
        raise AssertionError(row)


def test_the_symmetric_residue_of_the_scalar_is_accepted() -> None:
    mod = load()
    cells = fixture(mod)
    cells[1]["scalar"] = [1, 1, cells[1]["scalar"][2] - 32029]
    if mod.problems(cells):
        raise AssertionError(mod.problems(cells))
