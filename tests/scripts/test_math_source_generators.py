"""Contracts for math_source_generators: a read reaches the producer only as the digest-checked bytes of the
checkout, and a write refuses a symbolic-link target.

Each test builds a gororoba-math checkout and a repository root in tmp_path; the producer is cd_sign_rocq_ast, run
against a stub proof whose generated blocks the producer fills in.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
from pathlib import Path

import math_source_generators as runner
import pytest

import math_sources

NAME = "CdSignPythonSemantics.v"
STUB = "".join(
    f"(* BEGIN {block}: generated by scripts/cd_sign_rocq_ast.py *)\n(* END {block} *)\n"
    for block in ("cd_sign_ast", "cd_sign_mutant_ast")
)


def git(directory: Path, *arguments: str) -> str:
    return subprocess.run(
        [
            "git",
            "-C",
            str(directory),
            "-c",
            "core.fsmonitor=false",
            "-c",
            "user.name=t",
            "-c",
            "user.email=t@e.invalid",
            *arguments,
        ],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


@pytest.fixture
def checkout(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> tuple[Path, Path]:
    """A math checkout holding the generated proof, a root whose ledger records its digest, and the pin."""
    math = tmp_path / "math"
    (math / "rocq/quantum").mkdir(parents=True)
    (math / "rocq/quantum/_RocqProject").write_text(f'-Q . ""\n{NAME}\n', encoding="utf-8")
    (math / "rocq/quantum" / NAME).write_text(STUB, encoding="utf-8")
    git(math, "init", "-q")
    git(math, "add", ".")
    git(math, "commit", "-q", "-m", "stub")
    root = tmp_path / "root"
    (root / "docs/state").mkdir(parents=True)
    (root / "docs/state/research_state.json").write_text(json.dumps({"claims": []}), encoding="utf-8")
    (root / "docs/evidence/bundle").mkdir(parents=True)
    (root / "ci").mkdir()
    (root / "ci/gororoba_math.pin").write_text(git(math, "rev-parse", "HEAD") + "\n", encoding="utf-8")
    monkeypatch.setattr(runner, "ROOT", root)
    monkeypatch.setenv("GOROROBA_MATH", str(math))
    if runner.main(["cd_sign_rocq_ast", "--write"]) != 0:
        raise AssertionError("the stub could not be generated")
    digest = hashlib.sha256((math / "rocq/quantum" / NAME).read_bytes()).hexdigest()
    (root / "docs/evidence/bundle/source_hashes.sha256").write_text(f"{digest}  proofs/{NAME}\n", encoding="utf-8")
    git(math, "commit", "-q", "-am", "generated")
    (root / "ci/gororoba_math.pin").write_text(git(math, "rev-parse", "HEAD") + "\n", encoding="utf-8")
    return root, math


def test_check_passes_on_the_generated_source(checkout: tuple[Path, Path]) -> None:
    if runner.main(["cd_sign_rocq_ast", "--check"]) != 0:
        raise AssertionError("the generated, digest-bound source fails its own check")


def test_check_fails_on_an_edited_source(checkout: tuple[Path, Path], capsys: pytest.CaptureFixture[str]) -> None:
    _root, math = checkout
    path = math / "rocq/quantum" / NAME
    path.write_text(path.read_text(encoding="utf-8") + "(* edited *)\n", encoding="utf-8")
    if (
        runner.main(["cd_sign_rocq_ast", "--check"]) == 0
        or "differs from the retained digest" not in capsys.readouterr().err
    ):
        raise AssertionError("an edited source was compared against the generator")


def test_check_and_write_refuse_a_linked_target(checkout: tuple[Path, Path], tmp_path: Path) -> None:
    _root, math = checkout
    path = math / "rocq/quantum" / NAME
    outside = tmp_path / "outside.v"
    outside.write_bytes(path.read_bytes())
    path.unlink()
    path.symlink_to(outside)
    before = outside.read_bytes()
    if runner.main(["cd_sign_rocq_ast", "--check"]) != 2:
        raise AssertionError("--check read through a symbolic link")
    if runner.main(["cd_sign_rocq_ast", "--write"]) != 2 or outside.read_bytes() != before:
        raise AssertionError("--write wrote through a symbolic link")


def test_check_needs_the_pin_and_the_variable(checkout: tuple[Path, Path], monkeypatch: pytest.MonkeyPatch) -> None:
    root, _math = checkout
    (root / "ci/gororoba_math.pin").write_text("0" * 40 + "\n", encoding="utf-8")
    if runner.main(["cd_sign_rocq_ast", "--check"]) != 2:
        raise AssertionError("--check ran off the pin")
    monkeypatch.delenv("GOROROBA_MATH")
    if runner.main(["cd_sign_rocq_ast", "--check"]) != 2:
        raise AssertionError("--check ran with the variable unset")
    if math_sources.ENVIRONMENT_VARIABLE != "GOROROBA_MATH":
        raise AssertionError("the variable name changed")
