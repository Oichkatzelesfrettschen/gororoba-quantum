"""Contracts for cd_sign_rocq_ast: the Rocq terms in proofs/CdSignPythonSemantics.v are the serialized syntax tree
of cd_core.cd_sign and of its high-low-unconditional mutant, the mutation changes the term, a construct outside
the Rocq syntax is rejected rather than dropped, and the guards _dimension and _index behave on ints as the Rocq
builtin clauses state, reject bool and non-int dimensions, and pass an __index__ object on as a Python int.
"""

from __future__ import annotations

import ast
import hashlib
from collections.abc import Callable
from typing import cast

import cd_sign_rocq_ast as extract
import numpy as np
import pytest

import cd_core


def test_proof_terms_match_cd_core_source() -> None:
    generated = extract.terms(extract.SOURCE.read_text(encoding="utf-8"))
    proof = extract.PROOF.read_text(encoding="utf-8")
    for name, term in generated.items():
        if extract.embedded(proof, name) != term:
            raise AssertionError(f"{name} in {extract.PROOF.name} differs from the syntax tree of cd_core.cd_sign")


def test_mutant_term_differs_from_cd_sign_term() -> None:
    generated = extract.terms(extract.SOURCE.read_text(encoding="utf-8"))
    original = generated["cd_sign_ast"].replace("cd_sign_ast", "")
    mutant = generated["cd_sign_mutant_ast"].replace("cd_sign_mutant_ast", "")
    if original == mutant or "NotEq" in mutant or "NotEq" not in original:
        raise AssertionError("the high-low mutation did not remove the q != 0 test from the term")


def test_edited_source_fails_the_comparison() -> None:
    source = extract.SOURCE.read_text(encoding="utf-8").replace("half >>= 1", "half >>= 2")
    proof = extract.PROOF.read_text(encoding="utf-8")
    if extract.embedded(proof, "cd_sign_ast") == extract.terms(source)["cd_sign_ast"]:
        raise AssertionError("a changed shift count left the generated term unchanged")


@pytest.mark.parametrize(
    "body",
    [
        "    for i in range(dim):\n        pass\n    return 1\n",
        "    return 0 <= p < dim\n",
        "    return p * q\n",
        "    while p:\n        p = 0\n    else:\n        p = 1\n    return p\n",
        "    return abs(x=p)\n",
    ],
)
def test_unsupported_construct_is_rejected(body: str) -> None:
    with pytest.raises(extract.UnsupportedNode):
        extract.function_term(f"def cd_sign(dim, p, q):\n{body}", "cd_sign", "cd_sign_ast")


def test_markers_must_be_unique() -> None:
    begin = "(* BEGIN cd_sign_ast: generated by scripts/cd_sign_rocq_ast.py *)\n"
    with pytest.raises(extract.UnsupportedNode):
        extract.embedded(begin + begin + "(* END cd_sign_ast *)", "cd_sign_ast")


# ast.dump digests (Python 3.13 and later) of the two guards whose int behavior the Rocq builtin clauses state. A
# change to either guard fails here until dimension_guard and index_guard in CdSignPythonSemantics.v are re-checked
# against the new body.
GUARD_DIGESTS = {
    "_dimension": "d2dfba87109707dff7fbf25599a91405822c1f74e8854cc1dbf4c08cba493161",
    "_index": "0cb3cf2d6723c907eb9fa0afc967055feb0dc77682bf404f2d8a0217e1ca32bf",
}


def test_guard_bodies_match_the_stated_semantics() -> None:
    tree = ast.parse(extract.SOURCE.read_text(encoding="utf-8"))
    bodies = {node.name: node for node in tree.body if isinstance(node, ast.FunctionDef)}
    for name, digest in GUARD_DIGESTS.items():
        if hashlib.sha256(ast.dump(bodies[name]).encode()).hexdigest() != digest:
            raise AssertionError(f"cd_core.{name} changed; re-check its Rocq builtin clause")


def _raises(call: Callable[..., object], *args: object) -> bool:
    try:
        call(*args)
    except ValueError:
        return True
    return False


@pytest.mark.parametrize("dim", range(-3, 71))
def test_guards_on_int_arguments_follow_the_rocq_clauses(dim: int) -> None:
    dimension_guard = dim >= 1 and dim & (dim - 1) == 0
    if _raises(cd_core._dimension, dim) == dimension_guard:
        raise AssertionError(f"_dimension({dim}) disagrees with dimension_guard")
    for index in range(-3, 71):
        index_guard = 0 <= index < dim
        if index_guard:
            if cd_core._index(dim, index) != index:
                raise AssertionError(f"_index({dim}, {index}) returned another value")
        elif not _raises(cd_core._index, dim, index):
            raise AssertionError(f"_index({dim}, {index}) did not raise")


def test_guards_reject_bool_and_convert_index_objects() -> None:
    if not _raises(cd_core._dimension, True) or not _raises(cd_core._index, 4, True):
        raise AssertionError("a bool argument passed a guard")
    if not _raises(cd_core._dimension, 4.0):
        raise AssertionError("a non-int dimension passed _dimension")
    value = cd_core._index(4, cast(int, np.int64(3)))
    if type(value) is not int or value != 3:
        raise AssertionError("_index did not return a Python int for an __index__ object")
