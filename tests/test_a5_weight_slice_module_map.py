"""The check of the weight-slice module-map record over Q(i), on a fixture built from the module's tables.

The retained record replays on demand through the gate core-a5-weight-slice-module-map of ci/gates.json.
"""

import importlib.util
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "docs/evidence/a5-kernel-attachments/weight_slice_module_map.py"


def load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("a5_weight_slice_module_map", SCRIPT)
    if spec is None or spec.loader is None:
        raise ImportError(SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def fixture(mod: ModuleType) -> list[dict[str, Any]]:
    cells = []
    for source, orbit, g in mod.CELLS:
        row = mod.expected(source, orbit, g)
        row["images"] = [list(pair) for pair in row["images"]]
        cells.append(row | {"relations_sha256": "0" * 64})
    return cells


def test_the_fixture_passes_and_holds_four_cells() -> None:
    mod = load()
    cells = fixture(mod)
    if len(cells) != 4 or mod.problems(cells):
        raise AssertionError(mod.problems(cells))


MUTATIONS = {
    "a two-dimensional solution space": lambda cells: cells[0].update(solutions=[2]),
    "a control system with a solution": lambda cells: cells[1].update(control_solutions=[1]),
    "a singular map": lambda cells: cells[2].update(det_nonzero=[0]),
    "a radical not generated by its linear forms": lambda cells: cells[3].update(generation=[5, 0]),
    "unequal Hilbert numerators": lambda cells: cells[2].update(numerator_identity=False),
    "relations that differ from the retained weight-slice record": lambda cells: cells[0].update(
        relations_match_retained=False
    ),
    "a changed image": lambda cells: cells[1]["images"][1].__setitem__(1, "(i)*y(5)"),
    "a cone with a second quadric": lambda cells: cells[3].update(cone=[5, 16, 2]),
    "a cell removed": lambda cells: cells.pop(),
    "an extra field": lambda cells: cells[0].update(note="x"),
}


@pytest.mark.parametrize("name", sorted(MUTATIONS))
def test_a_changed_record_is_reported(name: str) -> None:
    mod = load()
    cells = fixture(mod)
    MUTATIONS[name](cells)
    if not mod.problems(cells):
        raise AssertionError(f"{name}: the changed record passes")


def test_the_numerator_identity_separates_a_plane_from_a_line() -> None:
    mod = load()
    # K = (x^2) in k[x, y]: R = (x), A = K : R = (x), and R / K = (x) / (x^2) is the irrelevant ideal (y) of k[y].
    num_k, num_r, num_a = [1, 0, -1], [1, -1], [1, -1]
    if not mod.numerator_identity(num_k, num_r, num_a, 2):
        raise AssertionError("N_K - N_R = N_A - (1 - t)^2 for the double line")
    if mod.numerator_identity(num_k, num_r, [1, -2, 1], 2):
        raise AssertionError("the origin in place of the line passes")
