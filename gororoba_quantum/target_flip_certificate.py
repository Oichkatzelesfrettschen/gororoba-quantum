"""Bind finite Rocq witnesses to the N=21 target-flip compiler output.

Rocq evaluates every phase-controlled six-bit input against the modular
formula. The certificate proves Boolean permutation behavior; circuit
phases and clean-workspace behavior belong to the Qiskit Operator checks.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from modular_arithmetic import modular_permutation
from target_flip import CONTROLLED_CX_COST, TargetCube, target_flip_network

MULTIPLIERS = (2, 4, 16)
CERTIFICATE_PATH = Path(__file__).resolve().parents[1] / "proofs" / "TargetFlipN21.v"

PREAMBLE = """(** * Exact phase-controlled target-flip witnesses for N=21.

    Generated by gororoba_quantum/target_flip_certificate.py from
    target_flip.target_flip_network(modular_permutation(21, multiplier)).
    Run the exporter with --check to bind the source to the compiler.

    Bit 5 is the phase control; bits 0 through 4 encode the data register.
    The expected action fixes data 21 through 31 and all phase-zero inputs.
    The Boolean proof covers permutation behavior. Qiskit Operator checks
    cover circuit phases and clean-workspace restoration separately. *)

From Stdlib Require Import Arith PeanoNat Bool List Lia.
Import ListNotations.

Record target_cube := Cube {
  cube_target : nat;
  cube_mask : nat;
  cube_state : nat
}.

Definition cube_validb (cube : target_cube) : bool :=
  (cube_target cube <? 5) &&
  (cube_mask cube <? 32) &&
  (cube_state cube <? 32) &&
  Nat.eqb (Nat.land (cube_state cube) (cube_mask cube)) (cube_state cube) &&
  Nat.eqb (Nat.land (cube_mask cube) (2 ^ cube_target cube)) 0.

Definition apply_cube (cube : target_cube) (packed : nat) : nat :=
  if Nat.eqb (Nat.land packed (32 + cube_mask cube)) (32 + cube_state cube)
  then Nat.lxor packed (2 ^ cube_target cube)
  else packed.

Fixpoint apply_network (network : list target_cube) (packed : nat) : nat :=
  match network with
  | [] => packed
  | cube :: remainder => apply_network remainder (apply_cube cube packed)
  end.

Definition expected_mul (multiplier packed : nat) : nat :=
  let data := Nat.land packed 31 in
  if Nat.eqb (Nat.land packed 32) 32
  then 32 + (if data <? 21 then (multiplier * data) mod 21 else data)
  else packed.

Definition network_correctb (multiplier : nat) (network : list target_cube) : bool :=
  forallb
    (fun packed => Nat.eqb (apply_network network packed) (expected_mul multiplier packed))
    (seq 0 64).

Lemma finite_network_correct : forall multiplier network,
  network_correctb multiplier network = true ->
  forall packed, packed < 64 ->
    apply_network network packed = expected_mul multiplier packed.
Proof.
  intros multiplier network certificate packed packed_bound.
  unfold network_correctb in certificate.
  rewrite forallb_forall in certificate.
  apply Nat.eqb_eq.
  apply certificate.
  apply in_seq.
  lia.
Qed.

Lemma valid_cube_excludes_target : forall cube,
  cube_validb cube = true ->
  Nat.land (cube_mask cube) (2 ^ cube_target cube) = 0.
Proof.
  intros cube certificate.
  unfold cube_validb in certificate.
  apply andb_true_iff in certificate as [_ excluded].
  apply Nat.eqb_eq in excluded.
  exact excluded.
Qed.

Lemma valid_network_excludes_targets : forall network,
  forallb cube_validb network = true ->
  forall cube, In cube network ->
    Nat.land (cube_mask cube) (2 ^ cube_target cube) = 0.
Proof.
  intros network certificate cube member.
  rewrite forallb_forall in certificate.
  apply valid_cube_excludes_target.
  apply certificate.
  exact member.
Qed.

"""


def certificate_networks() -> tuple[tuple[int, tuple[TargetCube, ...]], ...]:
    """Read the complete compiler witnesses and reject malformed cubes."""
    networks = tuple(
        (multiplier, target_flip_network(modular_permutation(21, multiplier))) for multiplier in MULTIPLIERS
    )
    for multiplier, network in networks:
        for cube in network:
            if not 0 <= cube.target < 5 or not 0 <= cube.control_mask < 32 or not 0 <= cube.control_state < 32:
                raise RuntimeError(f"multiplier {multiplier} has an out-of-register cube")
            if cube.control_state & cube.control_mask != cube.control_state or cube.control_mask & (1 << cube.target):
                raise RuntimeError(f"multiplier {multiplier} has a malformed control predicate")
    return networks


def certificate_source(networks: tuple[tuple[int, tuple[TargetCube, ...]], ...]) -> str:
    """Emit independent Nat.land/lxor evaluation and complete finite proofs."""
    blocks = [PREAMBLE]
    for multiplier, network in networks:
        controlled_cx_cost = sum(CONTROLLED_CX_COST[cube.control_mask.bit_count()] for cube in network)
        cubes = ";\n    ".join(f"Cube {cube.target} {cube.control_mask} {cube.control_state}" for cube in network)
        blocks.append(
            f"""(** Multiplier {multiplier}: {len(network)} target flips;
    phase-controlled CX surrogate {controlled_cx_cost}, before routing. *)
Definition network_{multiplier} : list target_cube :=
  [ {cubes} ].

Lemma network_{multiplier}_valid : forallb cube_validb network_{multiplier} = true.
Proof. vm_compute. reflexivity. Qed.

Lemma network_{multiplier}_finite : network_correctb {multiplier} network_{multiplier} = true.
Proof. vm_compute. reflexivity. Qed.

Theorem network_{multiplier}_correct : forall packed, packed < 64 ->
  apply_network network_{multiplier} packed = expected_mul {multiplier} packed.
Proof.
  apply finite_network_correct.
  exact network_{multiplier}_finite.
Qed.

Theorem network_{multiplier}_targets_excluded : forall cube, In cube network_{multiplier} ->
  Nat.land (cube_mask cube) (2 ^ cube_target cube) = 0.
Proof.
  apply valid_network_excludes_targets.
  exact network_{multiplier}_valid.
Qed.

Print Assumptions network_{multiplier}_correct.
Print Assumptions network_{multiplier}_targets_excluded.

"""
        )
    return "".join(blocks)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    actions = parser.add_mutually_exclusive_group(required=True)
    actions.add_argument("--write", action="store_true", help="write the generated certificate")
    actions.add_argument("--check", action="store_true", help="require exact compiler-to-certificate source agreement")
    parser.add_argument("--output", type=Path, default=CERTIFICATE_PATH, help="certificate source destination")
    arguments = parser.parse_args()
    networks = certificate_networks()
    source = certificate_source(networks)
    output: Path = arguments.output
    if arguments.write:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(source, encoding="utf-8")
    elif not output.is_file() or output.read_text(encoding="utf-8") != source:
        parser.exit(1, "certificate source differs from the actual N=21 target-flip compiler witnesses\n")
    for multiplier, network in networks:
        controlled_cx_cost = sum(CONTROLLED_CX_COST[cube.control_mask.bit_count()] for cube in network)
        print(
            f"N=21 multiplier={multiplier}: target_flips={len(network)}, controlled_cx_surrogate={controlled_cx_cost}"
        )
    print(f"certificate {'written' if arguments.write else 'fresh'}; 3 networks, 192 packed inputs")


if __name__ == "__main__":
    main()
