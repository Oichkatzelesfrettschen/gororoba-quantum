(** The twisted product of the W8 closure ideal of A_5 as polynomial identities.

    Over a commutative ring that holds i with i i = -1 and the inverse of 2,
    write a 32-coordinate point as x = (x_0, ..., x_15 | x_16, ..., x_31),
    z_k = x_k + i x_(16+k) and z'_k = x_k - i x_(16+k) for 0 <= k < 16. The
    W8 equations of docs/evidence/a5-w8-twisted-product/ideal_W8.sing are the
    real and imaginary parts of the sedenion zero-divisor equations
    y_0 = z_0, y_8 = z_8, U - V and W of the point z, with u = (z_1, ..., z_7),
    v = (z_9, ..., z_15), U = u.u, V = v.v and W = u.v. For each equation f,
    the functor Twisted proves, as identities in the coordinates x_k alone,
    f(z) = Re f + i Im f, f(z') = Re f - i Im f, Re f = (f(z) + f(z'))/2 and
    Im f = (f(z) - f(z'))/(2 i), with Re f and Im f the explicit polynomials
    of ideal_W8.sing (the four expansions reu_minus_v_expanded,
    imu_minus_v_expanded, rew_expanded and imw_expanded). The identities hold
    in every commutative ring with such an i and 1/2, so they hold in the
    polynomial ring of the 32 coordinates. W8_ideal_exchange states the
    consequence for every ideal I of the ring: I contains the eight real and
    imaginary parts exactly when it contains the eight forms f(z), f(z'), so
    the ideal of the W8 equations equals the ideal generated by J(z) and
    J(z') for the sedenion zero-divisor generators J.

    Remaining computed evidence (ledger row A5-223 of
    docs/evidence/a5-exceptional-fibers/ledger.tsv): that J(z) and J(z') use
    disjoint coordinate sets after the linear change z, z', so the variety is
    the product V(J) x V(J), and its dimension 24, its degree 16 and its first
    Hilbert numerator N_J(t)^2 (Singular, global dp ordering). No statement
    here concerns dimension or degree. *)

From Stdlib Require Import Ring ZArith Zmod.

Module Type TwistedRing.
  Parameter t : Type.
  Parameter zero one : t.
  Parameter add mul sub : t -> t -> t.
  Parameter opp : t -> t.
  Axiom ring_th : ring_theory zero one add mul sub opp (@eq t).
  Parameter i inv2 : t.
  Axiom i_squared : mul i i = opp one.
  Axiom two_inverse : mul (add one one) inv2 = one.
End TwistedRing.

Module Twisted (D : TwistedRing).
  Add Ring twisted_ring : D.ring_th.

  Declare Scope twisted_scope.
  Local Infix "+" := D.add : twisted_scope.
  Local Infix "*" := D.mul : twisted_scope.
  Local Infix "-" := D.sub : twisted_scope.
  Local Notation "- x" := (D.opp x) : twisted_scope.
  Local Open Scope twisted_scope.
  Local Abbreviation two := (D.one + D.one).
  Local Abbreviation i := D.i.
  Local Abbreviation inv2 := D.inv2.

  (** Seven-term sums over the index range 1 to 7. *)
  Definition sum7 (g : nat -> D.t) : D.t := g 1 + g 2 + g 3 + g 4 + g 5 + g 6 + g 7.

  Lemma sum7_ext (g h : nat -> D.t) : (forall k, g k = h k) -> sum7 g = sum7 h.
  Proof. intro H. unfold sum7. rewrite (H 1), (H 2), (H 3), (H 4), (H 5), (H 6), (H 7). reflexivity. Qed.

  Lemma sum7_lin (c : D.t) (a b : nat -> D.t) :
    sum7 (fun k => a k + c * b k) = sum7 a + c * sum7 b.
  Proof. unfold sum7. ring. Qed.

  Lemma sum7_lin_sub (c : D.t) (a b : nat -> D.t) :
    sum7 (fun k => a k - c * b k) = sum7 a - c * sum7 b.
  Proof. unfold sum7. ring. Qed.

  (** The complex product of two coordinate pairs, with i i = -1. *)
  Lemma pair_product (a b c d : D.t) :
    (a + i * b) * (c + i * d) = (a * c - b * d) + i * (a * d + b * c).
  Proof.
    transitivity ((a * c - b * d) + i * (a * d + b * c) + (i * i + D.one) * (b * d)); [ring|].
    rewrite D.i_squared. ring.
  Qed.

  Lemma pair_product_conjugate (a b c d : D.t) :
    (a - i * b) * (c - i * d) = (a * c - b * d) - i * (a * d + b * c).
  Proof.
    transitivity ((a * c - b * d) - i * (a * d + b * c) + (i * i + D.one) * (b * d)); [ring|].
    rewrite D.i_squared. ring.
  Qed.

  Lemma real_part_from_sum (re im fz fz' : D.t) :
    fz = re + i * im -> fz' = re - i * im -> re = inv2 * (fz + fz').
  Proof.
    intros Hz Hz'. rewrite Hz, Hz'.
    transitivity ((two * inv2) * re); [|ring].
    rewrite D.two_inverse. ring.
  Qed.

  Lemma imaginary_part_from_difference (re im fz fz' : D.t) :
    fz = re + i * im -> fz' = re - i * im -> im = (- i) * inv2 * (fz - fz').
  Proof.
    intros Hz Hz'. rewrite Hz, Hz'.
    transitivity ((- (i * i)) * (two * inv2) * im); [|ring].
    rewrite D.i_squared, D.two_inverse. ring.
  Qed.

  (** The ideal statement: an ideal I of the ring contains the pair f(z),
      f(z') exactly when it contains the pair Re f, Im f. *)
  Definition is_ideal (I : D.t -> Prop) : Prop :=
    (forall a b, I a -> I b -> I (a + b)) /\ (forall c a, I a -> I (c * a)).

  Theorem ideal_exchange (I : D.t -> Prop) (re im fz fz' : D.t) :
    is_ideal I -> fz = re + i * im -> fz' = re - i * im ->
    (I fz /\ I fz' <-> I re /\ I im).
  Proof.
    intros [Hadd Hmul] Hz Hz'. split.
    - intros [Iz Iz']. split.
      + rewrite (real_part_from_sum re im fz fz' Hz Hz'). apply Hmul. apply Hadd; assumption.
      + rewrite (imaginary_part_from_difference re im fz fz' Hz Hz').
        apply Hmul. replace (fz - fz') with (fz + (- D.one) * fz') by ring. apply Hadd; [assumption|].
        apply Hmul. assumption.
    - intros [Ire Iim]. rewrite Hz, Hz'. split.
      + apply Hadd; [assumption|]. apply Hmul. assumption.
      + replace (re - i * im) with (re + (- i) * im) by ring. apply Hadd; [assumption|]. apply Hmul. assumption.
  Qed.

  Section Coordinates.
    Variable X : nat -> D.t.

    Definition zeta (k : nat) : D.t := X k + i * X (16 + k).
    Definition zeta_conjugate (k : nat) : D.t := X k - i * X (16 + k).

    (** The bilinear form sum over 1 <= k <= 7 of z_(p k) z_(q k) and its
        real and imaginary parts. *)
    Definition form (p q : nat -> nat) (z : nat -> D.t) : D.t := sum7 (fun k => z (p k) * z (q k)).
    Definition form_re (p q : nat -> nat) : D.t :=
      sum7 (fun k => X (p k) * X (q k) - X (16 + p k) * X (16 + q k)).
    Definition form_im (p q : nat -> nat) : D.t :=
      sum7 (fun k => X (p k) * X (16 + q k) + X (16 + p k) * X (q k)).

    Lemma form_twisted (p q : nat -> nat) : form p q zeta = form_re p q + i * form_im p q.
    Proof.
      unfold form, form_re, form_im, zeta.
      rewrite <- sum7_lin. apply sum7_ext. intro k. apply pair_product.
    Qed.

    Lemma form_twisted_conjugate (p q : nat -> nat) :
      form p q zeta_conjugate = form_re p q - i * form_im p q.
    Proof.
      unfold form, form_re, form_im, zeta_conjugate.
      rewrite <- sum7_lin_sub. apply sum7_ext. intro k. apply pair_product_conjugate.
    Qed.

    Definition index_u (k : nat) : nat := k.
    Definition index_v (k : nat) : nat := 8 + k.

    (** U - V, with U = u.u and V = v.v. *)
    Definition eq_uv (z : nat -> D.t) : D.t := form index_u index_u z - form index_v index_v z.
    Definition eq_uv_re : D.t := form_re index_u index_u - form_re index_v index_v.
    Definition eq_uv_im : D.t := form_im index_u index_u - form_im index_v index_v.
    (** W = u.v. *)
    Definition eq_w (z : nat -> D.t) : D.t := form index_u index_v z.
    Definition eq_w_re : D.t := form_re index_u index_v.
    Definition eq_w_im : D.t := form_im index_u index_v.

    Theorem eq_uv_twisted : eq_uv zeta = eq_uv_re + i * eq_uv_im.
    Proof.
      unfold eq_uv, eq_uv_re, eq_uv_im. rewrite !form_twisted. ring.
    Qed.

    Theorem eq_uv_twisted_conjugate : eq_uv zeta_conjugate = eq_uv_re - i * eq_uv_im.
    Proof.
      unfold eq_uv, eq_uv_re, eq_uv_im. rewrite !form_twisted_conjugate. ring.
    Qed.

    Theorem eq_w_twisted : eq_w zeta = eq_w_re + i * eq_w_im.
    Proof. unfold eq_w, eq_w_re, eq_w_im. apply form_twisted. Qed.

    Theorem eq_w_twisted_conjugate : eq_w zeta_conjugate = eq_w_re - i * eq_w_im.
    Proof. unfold eq_w, eq_w_re, eq_w_im. apply form_twisted_conjugate. Qed.

    Theorem eq_uv_real_part : eq_uv_re = inv2 * (eq_uv zeta + eq_uv zeta_conjugate).
    Proof. exact (real_part_from_sum _ _ _ _ eq_uv_twisted eq_uv_twisted_conjugate). Qed.

    Theorem eq_uv_imaginary_part : eq_uv_im = (- i) * inv2 * (eq_uv zeta - eq_uv zeta_conjugate).
    Proof. exact (imaginary_part_from_difference _ _ _ _ eq_uv_twisted eq_uv_twisted_conjugate). Qed.

    Theorem eq_w_real_part : eq_w_re = inv2 * (eq_w zeta + eq_w zeta_conjugate).
    Proof. exact (real_part_from_sum _ _ _ _ eq_w_twisted eq_w_twisted_conjugate). Qed.

    Theorem eq_w_imaginary_part : eq_w_im = (- i) * inv2 * (eq_w zeta - eq_w zeta_conjugate).
    Proof. exact (imaginary_part_from_difference _ _ _ _ eq_w_twisted eq_w_twisted_conjugate). Qed.

    (** The linear equations y_0 = z_0 and y_8 = z_8 have real part x_k and
        imaginary part x_(16+k). *)
    Theorem linear_twisted (k : nat) :
      zeta k = X k + i * X (16 + k) /\ zeta_conjugate k = X k - i * X (16 + k).
    Proof. split; reflexivity. Qed.

    (** The expansions in the coordinates of ideal_W8.sing. *)

    Theorem eq_uv_re_expanded : eq_uv_re =
      ((((((((((((((((((((((((((((X 1 * X 1) + (X 2 * X 2)) + (X 3 * X 3)) + (X 4 * X 4)) + (X 5 * X 5)) + (X 6 * X 6)) + (X 7 * X 7)) - (X 9 * X 9)) - (X 10 * X 10)) - (X 11 * X 11)) - (X 12 * X 12)) - (X 13 * X 13)) - (X 14 * X 14)) - (X 15 * X 15)) - (X 17 * X 17)) - (X 18 * X 18)) - (X 19 * X 19)) - (X 20 * X 20)) - (X 21 * X 21)) - (X 22 * X 22)) - (X 23 * X 23)) + (X 25 * X 25)) + (X 26 * X 26)) + (X 27 * X 27)) + (X 28 * X 28)) + (X 29 * X 29)) + (X 30 * X 30)) + (X 31 * X 31)).
    Proof. unfold eq_uv_re, form_re, index_u, index_v, sum7. cbv beta. simpl Nat.add. ring. Qed.

    Theorem eq_uv_im_expanded : eq_uv_im =
      ((((((((((((((two * (X 1 * X 17)) + (two * (X 2 * X 18))) + (two * (X 3 * X 19))) + (two * (X 4 * X 20))) + (two * (X 5 * X 21))) + (two * (X 6 * X 22))) + (two * (X 7 * X 23))) - (two * (X 9 * X 25))) - (two * (X 10 * X 26))) - (two * (X 11 * X 27))) - (two * (X 12 * X 28))) - (two * (X 13 * X 29))) - (two * (X 14 * X 30))) - (two * (X 15 * X 31))).
    Proof. unfold eq_uv_im, form_im, index_u, index_v, sum7. cbv beta. simpl Nat.add. ring. Qed.

    Theorem eq_w_re_expanded : eq_w_re =
      ((((((((((((((X 1 * X 9) + (X 2 * X 10)) + (X 3 * X 11)) + (X 4 * X 12)) + (X 5 * X 13)) + (X 6 * X 14)) + (X 7 * X 15)) - (X 17 * X 25)) - (X 18 * X 26)) - (X 19 * X 27)) - (X 20 * X 28)) - (X 21 * X 29)) - (X 22 * X 30)) - (X 23 * X 31)).
    Proof. unfold eq_w_re, form_re, index_u, index_v, sum7. cbv beta. simpl Nat.add. ring. Qed.

    Theorem eq_w_im_expanded : eq_w_im =
      ((((((((((((((X 9 * X 17) + (X 10 * X 18)) + (X 11 * X 19)) + (X 12 * X 20)) + (X 13 * X 21)) + (X 14 * X 22)) + (X 15 * X 23)) + (X 1 * X 25)) + (X 2 * X 26)) + (X 3 * X 27)) + (X 4 * X 28)) + (X 5 * X 29)) + (X 6 * X 30)) + (X 7 * X 31)).
    Proof. unfold eq_w_im, form_im, index_u, index_v, sum7. cbv beta. simpl Nat.add. ring. Qed.

    (** The ideal of the real and imaginary parts equals the ideal of the
        forms of z and z', for every ideal of the coefficient ring. *)
    Theorem W8_ideal_exchange (I : D.t -> Prop) :
      is_ideal I ->
      (I (X 0 + i * X 16) /\ I (X 0 - i * X 16) /\ I (X 8 + i * X 24) /\ I (X 8 - i * X 24) /\
       I (eq_uv zeta) /\ I (eq_uv zeta_conjugate) /\ I (eq_w zeta) /\ I (eq_w zeta_conjugate)) <->
      (I (X 0) /\ I (X 16) /\ I (X 8) /\ I (X 24) /\
       I eq_uv_re /\ I eq_uv_im /\ I eq_w_re /\ I eq_w_im).
    Proof.
      intro H.
      pose proof (ideal_exchange I (X 0) (X 16) (X 0 + i * X 16) (X 0 - i * X 16) H eq_refl eq_refl) as lin0.
      pose proof (ideal_exchange I (X 8) (X 24) (X 8 + i * X 24) (X 8 - i * X 24) H eq_refl eq_refl) as lin8.
      pose proof (ideal_exchange I _ _ _ _ H eq_uv_twisted eq_uv_twisted_conjugate) as uv.
      pose proof (ideal_exchange I _ _ _ _ H eq_w_twisted eq_w_twisted_conjugate) as w.
      tauto.
    Qed.
  End Coordinates.
End Twisted.

