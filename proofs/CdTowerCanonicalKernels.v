  TA.scale 5 2 (SA.basis 5 i) =
  TA.add 5 (source_map 5 Nm_back (TA.mul 5 Nm_point (SA.basis 5 i)))
           (source_comb 5 16 Nm_functionals Nm_vectors (SA.basis 5 i)).
