"""Hilbert function of the fiber cone of the same-sign X incidences by monomial linear algebra.

The slice of X- -> N- is the image of Phi(a, rho, sig, w) of ../arcs-x-same. Its coordinate ring at the origin,
completed, is the subring R = k[[t]] + (a, rho, sig) k[[a, rho, sig, w]] of k[[a, rho, sig, w]], t = w^2 / (1 + w):
the seven coordinates lie in it, and it is generated by them, since rho, w rho, sig, w sig, a, a w / (1 + w) and t
are combinations of the coordinates and x_n = (a, rho or sig) w^n satisfies x_n = t (x_(n-2) + x_(n-1)). So the
truncated ranks of the fiber cone need no standard basis: with n the maximal ideal of the power series ring,
V_N = k[a, rho, sig, w] / n^N, A_d the image of I^d and B_d the image of m_R I^d,

    r_N(d) = dim A_d - dim B_d  <=  h_d = dim I^d / m_R I^d,

with equality for N large, and A_d = sum_j g_j A_(d-1), B_d = sum_j g_j B_(d-1) taken one order lower per unit of
the order of the generators. The script reports r_N(d) for the requested degrees and orders beside HF(k[y]/K2, d).

    $PYTHON docs/evidence/a5-exceptional-fibers/monomial-ladder/x_same_ladder.py --slug xm-nm --prime 32009 \
        --degree 3 --order 14
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
import time
from pathlib import Path
from typing import Any

import sympy
from flint import Ordering, nmod_mat, nmod_mpoly_ctx

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "kernel-limits"))
sys.path.insert(0, str(HERE.parents[3] / "gororoba_quantum"))

import plucker_limits as limits  # noqa: E402

SIGN = {"xm-nm": 1, "xp-np": -1}
NAMES = ("a", "rho", "sig", "w")


def truncate(ctx: Any, poly: Any, order: int) -> Any:
    return ctx.from_dict({e: c for e, c in poly.to_dict().items() if sum(e) < order})


def generators(slug: str, prime: int, order: int) -> list[Any]:
    """The header's G on Phi, modulo n^order."""
    ctx = nmod_mpoly_ctx.get(NAMES, ordering=Ordering.degrevlex, modulus=prime)
    a, rho, sig, w = ctx.gens()
    half = pow(2, -1, prime)
    u = sum(((-w) ** k for k in range(order)), ctx.from_dict({}))
    m = 1 + w
    t9 = truncate(ctx, -(w * w) * u * half, order)
    values = {
        "t1": a - t9,
        "t2": truncate(ctx, a * w * (w + 2) * u * half, order),
        "t4": (m * rho + sig) * half,
        "t5": (m * rho - sig) * half,
        "t6": (m * sig + rho) * half,
        "t7": (rho - m * sig) * half,
        "t9": t9 * SIGN[slug],
    }
    variables, _, ideal_g = limits.header(slug, prime)
    symbols = sympy.symbols(variables)
    powers: dict[tuple[str, int], Any] = {}

    def power(name: str, exponent: int) -> Any:
        if (name, exponent) not in powers:
            powers[name, exponent] = (
                values[name] if exponent == 1 else truncate(ctx, power(name, exponent - 1) * values[name], order)
            )
        return powers[name, exponent]

    out = []
    for text in ideal_g:
        polynomial = sympy.Poly(sympy.parse_expr(text.replace("^", "**")), *symbols)
        total = ctx.from_dict({})
        for exponents, coefficient in polynomial.terms():
            term = ctx.from_dict({(0, 0, 0, 0): int(coefficient.p) * pow(int(coefficient.q), -1, prime) % prime})
            for name, exponent in zip(variables, exponents, strict=True):
                if exponent:
                    term = truncate(ctx, term * power(name, exponent), order)
            total = total + term
        out.append(total)
    return out


def ring_basis(ctx: Any, order: int, maximal: bool) -> list[Any]:
    """A basis of R (of m_R when maximal) modulo n^order: the powers of t and the monomials outside k[w]."""
    a, rho, sig, w = ctx.gens()
    u = sum(((-w) ** k for k in range(order)), ctx.from_dict({}))
    t = truncate(ctx, w * w * u, order)
    out = []
    power = ctx.from_dict({(0, 0, 0, 0): 1})
    for n in range((order + 1) // 2):
        if n or not maximal:
            out.append(power)
        power = truncate(ctx, power * t, order)
    for exponents in itertools.product(range(order), repeat=4):
        if sum(exponents) < order and sum(exponents[:3]) >= 1:
            out.append(ctx.from_dict({exponents: 1}))
    return out


def rank_and_basis(ctx: Any, polys: list[Any], order: int, prime: int) -> tuple[int, list[Any]]:
    """Rank of the span of polys modulo n^order and an echelon basis of it."""
    index: dict[tuple[int, ...], int] = {}
    rows = []
    for poly in polys:
        row = {}
        for exponents, coefficient in poly.to_dict().items():
            if sum(exponents) < order:
                row[index.setdefault(tuple(int(v) for v in exponents), len(index))] = int(coefficient)
        rows.append(row)
    if not index:
        return 0, []
    matrix = nmod_mat(len(rows), len(index), prime)
    for i, row in enumerate(rows):
        for j, value in row.items():
            matrix[i, j] = value
    reduced, rank = matrix.rref()
    monomials: list[tuple[int, ...]] = [()] * len(index)
    for exponents, j in index.items():
        monomials[j] = exponents
    basis = []
    for i in range(rank):
        basis.append(ctx.from_dict({monomials[j]: int(reduced[i, j]) for j in range(len(index)) if int(reduced[i, j])}))
    return rank, basis


def ladder(slug: str, prime: int, degree: int, order: int) -> dict[str, Any]:
    started = time.time()
    ctx = nmod_mpoly_ctx.get(NAMES, ordering=Ordering.degrevlex, modulus=prime)
    gens = generators(slug, prime, order)
    low = int(min(min(sum(e) for e in g.to_dict()) for g in gens))
    # A_d and B_d modulo n^order come from A_(d-1) and B_(d-1) modulo n^(order - low).
    start = order - low * degree
    if start < 2:
        raise SystemExit(f"order {order} is below {low * degree + 2}")
    spaces = {"A": ring_basis(ctx, start, False), "B": ring_basis(ctx, start, True)}
    ranks: list[dict[str, int]] = []
    for d in range(1, degree + 1):
        current = start + low * d
        row = {"degree": d, "order": current}
        for key in ("A", "B"):
            products = [truncate(ctx, g * b, current) for g in gens for b in spaces[key]]
            rank, spaces[key] = rank_and_basis(ctx, products, current, prime)
            row[key] = rank
        row["r"] = row["A"] - row["B"]
        ranks.append(row)
    return {
        "slug": slug,
        "prime": prime,
        "order": order,
        "generator_order": low,
        "rows": ranks,
        "seconds": round(time.time() - started, 1),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--slug", choices=tuple(SIGN), default="xm-nm")
    parser.add_argument("--prime", type=int, choices=tuple(limits.PRIMES), default=32009)
    parser.add_argument("--degree", type=int, required=True)
    parser.add_argument("--order", type=int, required=True)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    record = ladder(args.slug, args.prime, args.degree, args.order)
    if args.out:
        args.out.write_text(json.dumps(record, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(record))


if __name__ == "__main__":
    main()
