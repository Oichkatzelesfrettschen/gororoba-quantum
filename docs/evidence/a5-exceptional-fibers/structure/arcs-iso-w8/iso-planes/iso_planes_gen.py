"""Write the Singular scripts of the point-blowup plane certificate for Iso -> N-.

Setting (Iso header iso-nm.sing, variables t2, t3, t4, t5, t6, t7; V(J) is the cone J = t2^2 + t4^2 - t5^2 - t6^2 +
t7^2 = 0 times the t3-axis; I = (G_1, ..., G_17)). B is the blowup of V(J) at the origin. In the chart t3 = s,
t_k = s u_k the exceptional divisor is {s = 0}, J(s u, s) = s^2 J'(u) and G_j(s u, s) = s^2 G'_j(s, u), so I O_B =
s^2 I'. The point (s, u) = (0, [0 : b : c : b : c]) lies on P(L0), the projectivization of the linear 3-space
L0 = {t2 = 0, t4 = t6, t5 = t7} on which G vanishes. As in the W8 certificate (../../c30-bounded/README.md), the fiber
cone of I' at p, cut by a slice transversal to P(L0), embeds as a linear space Pi_p in E0 = Proj F(I). The script
computes, at one point p and for a chosen smooth generator G'_ia:

  - the surface S = {J' = G'_ia = 0} of the slice v6 = v7 = 0, by Newton iteration over truncated power series in
    (s, v2),
  - the ideal I3 generated by the restrictions G'_j|_S / v2 (it equals the maximal ideal (s, v2)),
  - the 17 x 3 matrix M(p) of the generator classes G'_j in the basis G'_ia, v2 s, v2^2 of I'/m I',
  - the membership of Pi_p in V(K2),
  - the derivatives of M(p) with respect to the two coordinates of p (dual numbers), the rank of
    [M(p) | dM/db Y0 | dM/dc Y0], and the vanishing of the Jacobian of the generators of K2 against those vectors.

Randomness: the point and the vector Y0 take their values from DRAW, the uint16 values in [1, 32008] at index >= 5 in
index order (indices 0 to 4 belong to docs/evidence/quandela/permanent-estimators/permanent_probe.py); points.json
lists [index, value] per coefficient. Every value lies below both primes, so one integer serves both fields.

    $PYTHON iso_planes_gen.py            # writes points.json, sing/*.sing (run from any directory)
    $PYTHON iso_planes_gen.py --check    # regenerates in memory and requires every retained file to match
"""

import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[5]
REL = HERE.relative_to(ROOT).as_posix()
DRAW = "docs/evidence/anu_qrng/draw-2026-11-09T060635Z.json"
FIRST_INDEX = 5
W = "docs/evidence/a5-exceptional-fibers/working"
HEADERS = {
    32009: f"{W}/build/inputs/p32009-r10754/iso-nm.sing",
    32029: f"{W}/build/inputs/p32029-r9115/iso-nm.sing",
}
IMAG = {32009: 10754, 32029: 9115}
K2_FILE = {
    32009: f"{W}/runs/s3/iso_k2.rel",
    32029: f"{W}/distribute/out/a5-p2-iso/iso_p2/d2/relations-d2.rel",
}
GENS_FILE = {
    32009: f"{W}/distribute/out/a5-iso-d4/iso_p1/d2/gens.txt",
    32029: f"{W}/distribute/out/a5-p2-iso/iso_p2/d2/gens.txt",
}
PRIMES = (32009, 32029)
NGEN = 17
IA_MAIN = 9
IA_CROSS = 13
FIXED_B = 17
FIXED_C = 29
FIXED_Y0 = [3, 5, 7]
ON_POINT = {"a": 3, "c": 5, "d": 7, "t": 11}
MAXV = 32009  # every value is below the smaller prime, so one integer serves both fields


def take(values: list[int], count: int, start: int) -> tuple[list[list[int]], int]:
    """The next `count` draw values in [1, MAXV - 1] at index >= start, as [index, value], and the next start."""
    out: list[list[int]] = []
    pos = start
    while len(out) < count:
        if 0 < values[pos] < MAXV:
            out.append([pos, values[pos]])
        pos += 1
    return out, pos


def build_points() -> dict[str, list[list[int]]]:
    values = json.loads((ROOT / DRAW).read_text())["values"]
    pts: dict[str, list[list[int]]] = {}
    pos = FIRST_INDEX
    pts["plane-pt1"], pos = take(values, 5, pos)  # b, c, then Y0 (3 values)
    pts["base"], pos = take(values, 3, pos)  # s0, b, c of the off control
    return pts


def sha(path: str) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def case_name(kind: str, prime: int, tag: str = "") -> str:
    return f"iso-{kind}-p{prime}" + (f"-{tag}" if tag else "")


def template(name: str) -> str:
    """A Singular template of this directory; callers fill the placeholders."""
    return "\n" + (HERE / "templates" / f"{name}.sing").read_text()


def fill(text: str, prime: int, **kw: object) -> str:
    text = text.replace("@P@", str(prime)).replace("@NGEN@", str(NGEN)).replace("@NGEN1@", str(NGEN + 1))
    for key, val in kw.items():
        text = text.replace(f"@{key}@", str(val))
    return text


def preamble(name: str, prime: int, note: str, with_signs: bool = True) -> list[str]:
    header = HEADERS[prime]
    lines = [
        f"// {name}: {note}",
        f"// header {header} (sha256 {sha(header)}); values: {DRAW}, keys in points.json",
        'LIB "linalg.lib"; LIB "general.lib"; LIB "matrix.lib"; system("--ticks-per-sec",1); int t0=rtimer;',
        f'proc res(string m) {{ string l="RESULT {name} "+m; print(l); write(":a {REL}/logs/{name}.result", l); }}',
        f'< "{header}";',
    ]
    if with_signs:
        # the K2 relation file uses the generator order of the run that wrote it; eps maps the header's G to it
        lines += [
            f'execute("ideal Grun="+read("{GENS_FILE[prime]}")+";");',
            "intvec eps; int jj; for (jj=1;jj<=ncols(G);jj++) { if (Grun[jj]==G[jj]) { eps[jj]=1; } else {"
            ' if (Grun[jj]==-G[jj]) { eps[jj]=-1; } else { ERROR("generator "+string(jj)+" is not +-G"); } } }',
            'res("signs of the run generators against the header: "+string(eps));',
        ]
    return lines


def k2_loader(prime: int) -> list[str]:
    return [
        f'execute("ring Y={prime},(y(1..{NGEN})),dp;");',
        f'execute("ideal K="+read("{K2_FILE[prime]}")+";");',
    ]


def plane_script(prime: int, tag: str, ia: int, b: int, c: int, y0: list[int], cross: bool) -> str:
    name = case_name("plane", prime, tag)
    note = f"fiber-cone plane over the point [0:{b}:{c}:{b}:{c}] of P(L0), smooth generator G'_{ia}, prime {prime}"
    lines = preamble(name, prime, note)
    lines.append(f"int pb0={b}; int pc0={c}; int NN=10; int ia={ia}; intvec Y0={','.join(map(str, y0))};")
    lines.append(fill(template("dual"), prime))
    lines.append("// membership, Jacobian rank and tangent consistency")
    lines.extend(k2_loader(prime))
    mfile = f"{REL}/logs/{name}.M"
    lines.append(fill(template("plane-tests"), prime, MFILE=mfile))
    if cross:
        m0 = f"{REL}/logs/{case_name('plane', prime, 'pt1')}.M"
        lines.append(fill(template("cross"), prime, MFILE0=m0, IA0=IA_MAIN, IA1=ia))
    lines.append("quit;")
    return "\n".join(lines) + "\n"


def emq_script(prime: int) -> str:
    name = case_name("control-emq", prime)
    lines = preamble(name, prime, f"on control: limits [G_2(u)] over the exceptional divisor, prime {prime}")
    on = ON_POINT
    lines.append(fill(template("emq"), prime, I=IMAG[prime], UA=on["a"], UC=on["c"], UD=on["d"], UT=on["t"]))
    lines.extend(k2_loader(prime))
    lines.append(fill(template("emq-tests"), prime))
    lines.append("quit;")
    return "\n".join(lines) + "\n"


def base_script(prime: int, pts: dict[str, list[list[int]]]) -> str:
    name = case_name("control-base", prime)
    s0, b, c = (v for _, v in pts["base"])
    note = f"off control: first-order fiber over a point of L0 away from the origin, prime {prime}"
    lines = preamble(name, prime, note)
    lines.append(fill(template("base"), prime, S0=s0, B=b, C=c))
    lines.extend(k2_loader(prime))
    lines.append(fill(template("base-tests"), prime))
    lines.append("quit;")
    return "\n".join(lines) + "\n"


def l0_script(prime: int) -> str:
    name = case_name("l0", prime)
    lines = preamble(name, prime, f"G and J vanish identically on L0, prime {prime}", with_signs=False)
    lines.append(fill(template("l0"), prime))
    lines.append("quit;")
    return "\n".join(lines) + "\n"


def linear_script(prime: int) -> str:
    name = case_name("linear", prime)
    lines = preamble(name, prime, f"symbolic linear parts of J' and G' along P(L0), prime {prime}", with_signs=False)
    lines.append(fill(template("linear"), prime))
    lines.append("quit;")
    return "\n".join(lines) + "\n"


def k2_script(prime: int) -> str:
    name = case_name("k2", prime)
    lines = preamble(
        name,
        prime,
        f"dimension and degree of K2, minimal generators of the powers of (x, v2 s, v2^2), prime {prime}",
        with_signs=False,
    )
    lines.extend(k2_loader(prime))
    lines.append(
        "ideal Ks=std(K);\n"
        'res("K2: generators "+string(size(K))+", affine dimension "+string(dim(Ks))+", degree "+string(mult(Ks))'
        '+" (5 and 23 required), s "+string(rtimer-t0));'
    )
    lines.append(fill(template("cone"), prime))
    lines.append("quit;")
    return "\n".join(lines) + "\n"


def outputs() -> dict[Path, str]:
    """Every generated file as path -> text: points.json and the Singular scripts."""
    pts = build_points()
    ledger = {
        "draw": DRAW,
        "rule": f"uint16 values in [1, {MAXV - 1}] at zero-based index >= {FIRST_INDEX}, in index order; "
        "[index, value] per coefficient; the same integers serve both primes",
        "points": pts,
        "fixed": {
            "plane-pt2": {"b": FIXED_B, "c": FIXED_C, "y0": FIXED_Y0},
            "on-control": ON_POINT,
            "note": "hand-chosen points: a rank at any point of the family bounds the generic rank from below, "
            "so these need no random draw",
        },
    }
    out: dict[Path, str] = {HERE / "points.json": json.dumps(ledger, indent=1) + "\n"}
    vals = [v for _, v in pts["plane-pt1"]]
    b, c, y0 = vals[0], vals[1], vals[2:5]
    for prime in PRIMES:
        sing = HERE / "sing"
        out[sing / f"{case_name('l0', prime)}.sing"] = l0_script(prime)
        out[sing / f"{case_name('linear', prime)}.sing"] = linear_script(prime)
        out[sing / f"{case_name('k2', prime)}.sing"] = k2_script(prime)
        out[sing / f"{case_name('plane', prime, 'pt1')}.sing"] = plane_script(prime, "pt1", IA_MAIN, b, c, y0, False)
        out[sing / f"{case_name('plane', prime, 'pt1-ia13')}.sing"] = plane_script(
            prime, "pt1-ia13", IA_CROSS, b, c, y0, True
        )
        out[sing / f"{case_name('plane', prime, 'pt2')}.sing"] = plane_script(
            prime, "pt2", IA_MAIN, FIXED_B, FIXED_C, FIXED_Y0, False
        )
        out[sing / f"{case_name('control-emq', prime)}.sing"] = emq_script(prime)
        out[sing / f"{case_name('control-base', prime)}.sing"] = base_script(prime, pts)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="regenerate in memory and require every file to match")
    args = ap.parse_args()
    files = outputs()
    if args.check:
        bad = [str(p.relative_to(HERE)) for p, text in files.items() if not p.exists() or p.read_text() != text]
        if bad:
            raise SystemExit("generated files differ: " + ", ".join(bad))
        print(f"{len(files)} generated files match")
        return
    (HERE / "sing").mkdir(exist_ok=True)
    (HERE / "logs").mkdir(exist_ok=True)
    for path, text in files.items():
        path.write_text(text)
        print(path.relative_to(HERE))


if __name__ == "__main__":
    main()
