"""Write the Singular scripts of the bounded check whether the degree-30 component C30 of V(K2) lies in the W8 fiber.

Setting (W8 -> N-, header w8-nm.sing, variables t1, t2, t4, t5, t6, t7, t9, V(J) a hypersurface with an ordinary double
point at the origin, I = (G_1, ..., G_24)). B is the blowup of V(J) at the origin. In the chart t1 = s, t_i = s u_i
the exceptional quadric is {s = 0}, J(s, s u) = s^2 J'(s, u) and G_j(s, s u) = s^2 G'_j(s, u), so I O_B = s^2 I'. The
point (s, u) = (0, [1 : 0 : b : c : b : c : 0]) lies on P(L0), the projectivization of the linear 3-space L0 on which
G vanishes. Bl_{I'} B maps onto Bl_I V(J) and over the origin the two projective coordinates [G'] and [G] agree, so
the fibre cone of I' at a point p of P(L0), cut by a slice transversal to P(L0), embeds as a linear space Pi_p in the
fiber E0 = Proj F(I) of the origin (README.md of this directory). The script computes, at one point p:

  - the surface S = {G'_a = G'_b = 0} of the slice (a = 2, b = 11, the two generators with independent linear parts),
    by Newton iteration over truncated power series in (s, v2),
  - the ideal I''' generated by the restrictions G'_j|_S / v2 (it equals the maximal ideal (s, v2)),
  - the 24 x 4 matrix M(p) of the generator classes G'_j in the basis g1, g2, v2 s, v2^2 of I'/m I' (Pi_p is its
    column space),
  - the membership of Pi_p in V(K2), V(P) = C20, V(K2 : P) = C30 and V(Lambda) (the quotient and P exist at 32009),
  - the derivatives of M(p) with respect to the two coordinates of p (dual numbers), the rank of
    [M(p) | dM/db Y0 | dM/dc Y0], and the vanishing of the Jacobian of the generators of K2 and of K2 : P against
    those tangent vectors.

Randomness: every point, vector and form takes its values from DRAW (docs/evidence/anu_qrng), the uint16 values in
[1, 32008] in index order; points.json lists [index, value] per coefficient.

    $PYTHON c30_gen.py            # writes points.json, sing/*.sing (run from any directory)
    $PYTHON c30_gen.py --check    # regenerates in memory and requires every retained file to match
"""

import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
REL = HERE.relative_to(ROOT).as_posix()
DRAW = "docs/evidence/anu_qrng/draw-2026-11-08T182935Z.json"
W = "docs/evidence/a5-exceptional-fibers/working"
KP = "docs/evidence/a5-exceptional-fibers/structure/w8-kp"
HEADERS = {
    32009: f"{W}/build/inputs/p32009-r10754/w8-nm.sing",
    32029: f"{W}/build/inputs/p32029-r9115/w8-nm.sing",
}
K2_32029 = f"{W}/distribute/out/a5-p2-w8/w8_p2/d2/relations-upto-d2.rel"
LAMBDA = {
    32009: "y(22),y(19)+y(21),y(18),y(13)-y(23),y(11)+10754*y(23),y(8)+y(24),y(4)+y(12)-y(24),y(3),y(2)+10754*y(24)",
    32029: "y(22),y(19)+y(21),y(18),y(13)-y(23),y(11)+9115*y(23),y(8)+y(24),y(4)+y(12)-y(24),y(3),y(2)+9115*y(24)",
}
PLANE_POINTS = {32009: 3, 32029: 2}
NGEN = 24
MAXV = 32009  # every value is below the smaller prime, so one integer serves both fields


def case_name(kind: str, prime: int, tag: str = "") -> str:
    return f"c30-{kind}-p{prime}" + (f"-{tag}" if tag else "")


def take(values: list[int], count: int, start: int) -> tuple[list[list[int]], int]:
    """The next `count` draw values in [1, MAXV - 1] at index >= start, as [index, value], and the next start."""
    out: list[list[int]] = []
    pos = start
    while len(out) < count:
        if 0 < values[pos] < MAXV:
            out.append([pos, values[pos]])
        pos += 1
    return out, pos


def build_points() -> dict[str, list[list[int]]]:
    values = json.loads((ROOT / DRAW).read_text())["values"]
    pts: dict[str, list[list[int]]] = {}
    pos = 0
    for prime, count in PLANE_POINTS.items():
        for n in range(1, count + 1):
            got, pos = take(values, 6, pos)  # b, c, then Y0 (4 values)
            pts[f"plane-p{prime}-pt{n}"] = got
    for prime in PLANE_POINTS:
        got, pos = take(values, 5, pos)  # u2, u4, u5, u6, u7 of the on control
        pts[f"emq-p{prime}"] = got
    for prime in PLANE_POINTS:
        got, pos = take(values, 3, pos)  # s0, b, c of the off control
        pts[f"base-p{prime}"] = got
    for f in range(1, 6):
        got, pos = take(values, NGEN, pos)
        pts[f"slice-l{f}"] = got
    return pts


def sha(path: str) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def preamble(name: str, prime: int, note: str) -> list[str]:
    header = HEADERS[prime]
    return [
        f"// {name}: {note}",
        f"// header {header} (sha256 {sha(header)}); values: {DRAW}, keys in points.json",
        'LIB "linalg.lib"; LIB "general.lib"; LIB "matrix.lib"; system("--ticks-per-sec",1); int t0=rtimer;',
        f'proc res(string m) {{ string l="RESULT {name} "+m; print(l); write(":a {REL}/logs/{name}.result", l); }}',
        f'< "{header}";',
    ]


def kp_loader(prime: int) -> list[str]:
    """Singular lines that define ring Y with K (K2) and Lam, and at 32009 also P and Qq (K2 : P)."""
    if prime == 32009:
        return [
            f'< "{REL}/sing/kp-p32009.sing";',
            f'execute("ideal Qq="+read("{KP}/quotient.txt")+";");',
            f"ideal Lam={LAMBDA[32009]};",
        ]
    return [
        f"ring Y={prime},(y(1..24)),dp;",
        f'execute("ideal K="+read("{K2_32029}")+";");',
        f"ideal Lam={LAMBDA[32029]};",
    ]


def kp_file() -> str:
    """ring Y with K and P at 32009, copied from check.sing of w8-kp (line 1 ring, lines 2-145 K, line 146 P)."""
    lines = (ROOT / KP / "check.sing").read_text().splitlines()
    return "\n".join([lines[0], *lines[1:145], lines[145]]) + "\n"


def plane_script(prime: int, n: int, pts: dict[str, list[list[int]]]) -> str:
    name = case_name("plane", prime, f"pt{n}")
    vals = [v for _, v in pts[f"plane-p{prime}-pt{n}"]]
    b, c, y0 = vals[0], vals[1], vals[2:6]
    L = preamble(name, prime, f"fibre-cone plane over the point [1:0:{b}:{c}:{b}:{c}:0] of P(L0), prime {prime}")
    L.append(f"int pb0={b}; int pc0={c}; int NN=10; int ia=2; int ib=11; intvec Y0={','.join(map(str, y0))};")
    L.append(template("dual").replace("@P@", str(prime)))
    L.append("// membership, Jacobian rank and tangent consistency")
    L.extend(kp_loader(prime))
    L.append(template("plane-tests").replace("@P@", str(prime)).replace("@HAS_P@", "1" if prime == 32009 else "0"))
    L.append("quit;")
    return "\n".join(L) + "\n"


def emq_script(prime: int, pts: dict[str, list[list[int]]]) -> str:
    name = case_name("control-emq", prime)
    u = [v for _, v in pts[f"emq-p{prime}"]]
    L = preamble(
        name, prime, f"on control: the point blowup family, limits [G_2(u)] over the exceptional quadric, prime {prime}"
    )
    L.append(template("emq").replace("@P@", str(prime)).replace("@U@", ",".join(map(str, u))))
    L.extend(kp_loader(prime))
    L.append(template("emq-tests").replace("@HAS_P@", "1" if prime == 32009 else "0"))
    L.append("quit;")
    return "\n".join(L) + "\n"


def base_script(prime: int, pts: dict[str, list[list[int]]]) -> str:
    name = case_name("control-base", prime)
    s0, b, c = [v for _, v in pts[f"base-p{prime}"]]
    L = preamble(
        name,
        prime,
        f"off control: plane over a point of the strict transform of L0 outside the exceptional quadric, prime {prime}",
    )
    L.append(
        template("base")
        .replace("@P@", str(prime))
        .replace("@S0@", str(s0))
        .replace("@B@", str(b))
        .replace("@C@", str(c))
    )
    L.extend(kp_loader(prime))
    L.append(template("base-tests").replace("@P@", str(prime)))
    L.append("quit;")
    return "\n".join(L) + "\n"


def slice_script(pts: dict[str, list[list[int]]]) -> str:
    prime = 32009
    name = case_name("global-slice-k5", prime)
    header = HEADERS[prime]
    L = [
        f"// {name}: five QRNG linear forms of G, saturation of (J, l1(G), ..., l5(G)) by t2 through the"
        " homogenized standard",
        "// basis (the t-space slice ladder, ../arcs-iso-w8/tslice/README.md) for W8;"
        f" header {header} (sha256 {sha(header)}); forms {DRAW}",
        'LIB "elim.lib"; LIB "general.lib"; system("--ticks-per-sec",1); int t0=rtimer; option(prot);',
        f'proc res(string m) {{ string l="RESULT {name} "+m; print(l); write(":a {REL}/logs/{name}.result", l); }}',
        f'< "{header}";',
    ]
    for f in range(1, 6):
        coeffs = [v for _, v in pts[f"slice-l{f}"]]
        L.append(f"poly l{f}=" + "+".join(f"{cf}*G[{j + 1}]" for j, cf in enumerate(coeffs)) + ";")
    L.append("ideal Q=J,l1,l2,l3,l4,l5;")
    L.append('res("start: variables "+string(nvars(basering))+", size(Q) "+string(size(Q))+", s "+string(rtimer-t0));')
    L.append(
        "ideal Qs=std(Q);\n"
        'res("standard basis of Q: generators "+string(size(Qs))+", s "+string(rtimer-t0));\n'
        f"ring rh={prime},(t1,t4,t5,t6,t7,t9,h,t2),dp;\n"
        "ideal Qh=homog(imap(r,Qs),h);\n"
        "ideal Sh=std(Qh);\n"
        'res("standard basis of the homogenization: generators "+string(size(Sh))+", s "+string(rtimer-t0));\n'
        "int ex=0; int ii; poly gg; int ee; for (ii=1;ii<=ncols(Sh);ii++) { gg=Sh[ii]; ee=0;"
        " while (gg!=0 && subst(gg,t2,0)==0) { gg=gg/t2; ee++; } Sh[ii]=gg; if (ee>ex) { ex=ee; } }\n"
        "ideal Sd=subst(Sh,h,1);\n"
        "setring r; ideal S=imap(rh,Sd); S=std(S);\n"
        'res("saturation by t2: dim "+string(dim(S))+" degree "+string(mult(S))+", s "+string(rtimer-t0));'
    )
    L.append("quit;")
    return "\n".join(L) + "\n"


TEMPLATES = HERE / "templates"


def template(name: str) -> str:
    """A Singular template of this directory; callers fill the placeholders @P@, @U@, @B@, @C@, @S0@ and @HAS_P@."""
    return "\n" + (TEMPLATES / f"{name}.sing").read_text()


def outputs() -> dict[Path, str]:
    """Every generated file as path -> text: points.json, kp-p32009.sing and the Singular scripts."""
    pts = build_points()
    ledger = {
        "draw": DRAW,
        "rule": "uint16 values in [1, 32008] in index order, zero-based; [index, value] per coefficient",
        "points": pts,
    }
    out: dict[Path, str] = {HERE / "points.json": json.dumps(ledger, indent=1) + "\n"}
    out[HERE / "sing" / "kp-p32009.sing"] = kp_file()
    for prime, count in PLANE_POINTS.items():
        for n in range(1, count + 1):
            out[HERE / "sing" / f"{case_name('plane', prime, f'pt{n}')}.sing"] = plane_script(prime, n, pts)
        out[HERE / "sing" / f"{case_name('control-emq', prime)}.sing"] = emq_script(prime, pts)
        out[HERE / "sing" / f"{case_name('control-base', prime)}.sing"] = base_script(prime, pts)
    out[HERE / "sing" / f"{case_name('global-slice-k5', 32009)}.sing"] = slice_script(pts)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="regenerate in memory and require every file to match")
    args = ap.parse_args()
    files = outputs()
    if args.check:
        bad = [str(p.relative_to(HERE)) for p, text in files.items() if not p.exists() or p.read_text() != text]
        if bad:
            raise SystemExit("generated files differ: " + ", ".join(bad))
        print(f"{len(files)} generated files match")
        return
    (HERE / "sing").mkdir(exist_ok=True)
    (HERE / "logs").mkdir(exist_ok=True)
    for path, text in files.items():
        path.write_text(text)
        print(path.relative_to(HERE))


if __name__ == "__main__":
    main()
