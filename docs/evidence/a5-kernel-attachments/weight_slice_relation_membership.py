"""Each degree-2 relation of the weight-slice producer lies in the relation ideal of the fiber cone.

`weight_slice_fiber_relations.py` reads the relations q of degree 2 as the syzygies of the normal forms of the
products P_ab = G_a G_b modulo H + T, with H = J + m (P_ab) and T an ideal of monomials. This producer certifies the
one statement the fiber-cone rows take from that computation: q(G) lies in H, that is, in J + m I^2 inside the
polynomial ring, hence in the local ring. It regenerates each of the ten cells over Q(i) and checks in the same
Singular session:

- every generator of J and every selected Pfaffian G_a is homogeneous for the torus weight w, so H is a
  homogeneous ideal for the grading by w, whose values are nonnegative integers;
- every generator of T is a monomial of weight above E, the largest weight of a product;
- for every relation q, the polynomial f = q(G) = sum_ab c_ab G_a G_b, formed from the unreduced products, has all
  its terms of weight at most E and reduces to zero modulo the standard basis of H + T.

Lemma (truncation). Let H be homogeneous for a grading with nonnegative integer weights and T an ideal generated by
monomials of weight above E. A polynomial f whose terms have weight at most E and that lies in H + T lies in H.
Proof: write f = h + t with h in H and t in T. For each weight v at most E the component of weight v satisfies
f_v = h_v + t_v; h_v lies in H because H is homogeneous, and t_v = 0 because T is spanned over the field by
monomials of weight above E. Summing over v gives f in H.

The standard basis of the producer is that of J + T + m (P_ab reduced modulo J), the same ideal as H + T, since each
reduced product differs from G_a G_b by an element of J. The control substitutes a single product G_a G_b with a
nonzero normal form for a relation: it is rejected.

Run from the repository root: "$PYTHON" docs/evidence/a5-kernel-attachments/weight_slice_relation_membership.py
[--check]
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import weight_slice_fiber_relations as ws  # noqa: E402

import parallel  # noqa: E402

RECORD = HERE / "weight-slice-relation-membership-result.json"
SCHEMA = "gororoba.a5.weight-slice-relation-membership/1"
INPUTS = ("weight_slice_relation_membership.py", "weight_slice_fiber_relations.py")
WEIGHT_SLICE = HERE / "weight-slice-fiber-relations-result.json"
CELLS: tuple[tuple[str, str], ...] = tuple((orbit, source) for orbit in ws.ORBITS for source in ws.SOURCES)

STAGE = """
int mfail=0; int mover=0; poly f; int ua; int ub;
for(ua=1;ua<=size(S);ua++){ f=0;
  for(ub=1;ub<=n;ub++){ if(S[ua][ub]!=0){ f=f+S[ua][ub]*G[IX[ub][1]]*G[IX[ub][2]]; } }
  if(tmax(f)>pmax){mover++;} if(reduce(f,sQ)!=0){mfail++;} }
print("RESULT membership_relations "+string(size(S)));
print("RESULT membership_failures "+string(mfail));
print("RESULT relations_above_truncation "+string(mover));
int tmin=-1; int tbad=0;
for(ua=1;ua<=ncols(TR2);ua++){ if(TR2[ua]!=0){
  if(size(TR2[ua])!=1){tbad++;} if(tmin<0 or tdeg(TR2[ua])<tmin){tmin=tdeg(TR2[ua]);} } }
print("RESULT truncation_bound "+string(pmax));
print("RESULT truncation_min_weight "+string(tmin));
print("RESULT truncation_non_monomials "+string(tbad));
int ginh=0; for(ua=1;ua<=g;ua++){ if(!thomog(G[ua])){ginh++;} }
print("RESULT generators_inhomogeneous "+string(ginh));
int crej=-1;
for(ub=1;ub<=n;ub++){ if(N[ub]!=0 and crej<0){ crej=(reduce(G[IX[ub][1]]*G[IX[ub][2]],sQ)!=0); } }
print("RESULT control_single_product_rejected "+string(crej));
"""


def certify(cell: tuple[str, str]) -> dict[str, Any]:
    orbit, source = cell
    marker = 'print("RESULT done 1");'
    script = ws.fiber_script(ws.orbit_task(orbit), source, 0, 0)
    if script.count(marker) != 1:
        raise RuntimeError("the weight-slice script has no single end marker")
    run = ws.run_singular(script.replace(marker, STAGE + marker))
    values = run["values"]
    return {
        "orbit": orbit,
        "source": source,
        "relations_sha256": ws.summarize_fiber_run(run)["relations_sha256"],
        "germ_inhomogeneous_generators": int(values["germ_inhomogeneous"][0]),
        "generators_inhomogeneous": int(values["generators_inhomogeneous"][0]),
        "relations": int(values["membership_relations"][0]),
        "membership_failures": int(values["membership_failures"][0]),
        "relations_above_truncation": int(values["relations_above_truncation"][0]),
        "truncation_bound": int(values["truncation_bound"][0]),
        "truncation_min_weight": int(values["truncation_min_weight"][0]),
        "truncation_non_monomials": int(values["truncation_non_monomials"][0]),
        "control_single_product_rejected": int(values["control_single_product_rejected"][0]),
    }


ZERO_KEYS = (
    "germ_inhomogeneous_generators",
    "generators_inhomogeneous",
    "membership_failures",
    "relations_above_truncation",
    "truncation_non_monomials",
)


def problems(record: dict[str, Any]) -> list[str]:
    """Every way the record fails the claim; an empty list is a pass."""
    found: list[str] = []
    if record.get("schema") != SCHEMA:
        found.append("schema differs")
    if record.get("field") != "Q(i)":
        found.append("the field differs from Q(i)")
    cells = record.get("cells", [])
    if [(cell.get("orbit"), cell.get("source")) for cell in cells] != list(CELLS):
        found.append("the cells are not the ten cells in order")
        return found
    for cell in cells:
        label = f"{cell['source']} {cell['orbit']}"
        for key in ZERO_KEYS:
            if cell.get(key) != 0:
                found.append(f"{label}: {key} is not zero")
        bound, lowest = cell.get("truncation_bound"), cell.get("truncation_min_weight")
        if not isinstance(bound, int) or not isinstance(lowest, int) or lowest <= bound:
            found.append(f"{label}: a truncation monomial has weight at most the bound")
        if cell.get("control_single_product_rejected") != 1:
            found.append(f"{label}: the control product is not rejected")
    if record.get("pass") is not (found == []):
        found.append("the pass flag differs from the verdict")
    return found


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def slice_problems(record: dict[str, Any]) -> list[str]:
    """Relation digest, relation count and truncation bound against the Q(i) cells of the weight-slice record."""
    retained = {
        (cell["orbit"], cell["source"]): cell
        for cell in json.loads(WEIGHT_SLICE.read_text(encoding="utf-8"))["cells"]
        if cell["characteristic"] == 0
    }
    found: list[str] = []
    for cell in record.get("cells", []):
        label = f"{cell['source']} {cell['orbit']}"
        other = retained.get((cell["orbit"], cell["source"]), {})
        if cell.get("relations_sha256") != other.get("relations_sha256"):
            found.append(f"{label}: the relations differ from those of the weight-slice record")
        if cell.get("relations") != other.get("relation_count"):
            found.append(f"{label}: the relation count differs from that of the weight-slice record")
        if cell.get("truncation_bound") != other.get("product_max_weight"):
            found.append(f"{label}: the truncation bound differs from the largest product weight of the record")
    return found


def build() -> dict[str, Any]:
    record: dict[str, Any] = {
        "schema": SCHEMA,
        "field": "Q(i)",
        "inputs": {name: _digest(HERE / name) for name in INPUTS},
        "weight_slice_record_sha256": _digest(WEIGHT_SLICE),
        "cells": parallel.ordered_map(certify, list(CELLS), min_items=2),
        "pass": True,
    }
    record["pass"] = problems(record) == []
    return record


def main() -> None:
    if "--check" in sys.argv[1:]:
        record = json.loads(RECORD.read_text(encoding="utf-8"))
        found = problems(record) + slice_problems(record)
        for name in INPUTS:
            if record["inputs"].get(name) != _digest(HERE / name):
                found.append(f"input digest of {name} differs")
        if record.get("weight_slice_record_sha256") != _digest(WEIGHT_SLICE):
            found.append("digest of the weight-slice record differs")
        if found:
            raise SystemExit("\n".join(found))
        print("weight-slice-relation-membership-result.json: pass")
        return
    record = build()
    found = problems(record) + slice_problems(record)
    RECORD.write_text(json.dumps(record, indent=1) + "\n", encoding="utf-8")
    print(json.dumps({"pass": record["pass"], "problems": found}, indent=1))
    if found:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
