"""Focused contracts for the nullity-sixteen bundle invariants."""

from __future__ import annotations

import unittest

import nullity_sixteen_bundle


class NullitySixteenBundleTests(unittest.TestCase):
    """Catch loss of the torsion K-class hidden from Chern classes."""

    def test_zero_c3_does_not_erase_the_nonzero_stable_complex_class(self) -> None:
        result = nullity_sixteen_bundle.bundle_checks()
        invariants = result["topology_and_characteristics"]

        self.assertTrue(result["pass"])
        self.assertEqual(invariants["complex_triviality"], "nontrivial")
        self.assertEqual(invariants["total_c3_mod_2"], 0)
        self.assertEqual(invariants["reduced_complex_k_group"], "Z/2 generated by x=[xi]-2")
        self.assertEqual(invariants["kernel_bundle_reduced_k_class"], "3x=x != 0")
        self.assertFalse(invariants["complex_stable_triviality"])

    def test_cell_complex_and_hodgkin_complex_agree_on_the_k_groups(self) -> None:
        result = nullity_sixteen_bundle.bundle_checks()
        topology = result["base_topology"]
        k_theory = result["representation_ring_k_theory"]

        self.assertEqual(topology["cell_degrees"], [0, 5, 6, 11])
        self.assertEqual(topology["cellular_boundary_maps"], {"6_to_5": 2})
        self.assertEqual(topology["integral_homology"], {"0": "Z", "5": "Z/2", "11": "Z"})
        self.assertEqual(topology["integral_cohomology"], {"0": "Z", "6": "Z/2", "11": "Z"})
        self.assertEqual(k_theory["koszul_relations"], ["2x", "x^2+8x"])
        self.assertEqual(k_theory["reduced_k0"], "Z/2")
        self.assertEqual(k_theory["k1"], "Z")
        self.assertTrue(k_theory["first_syzygy_verified"])
        self.assertTrue(k_theory["second_koszul_boundary_is_x_times_first_syzygy"])

    def test_reduced_transitions_and_each_irreducible_have_the_claimed_types(self) -> None:
        result = nullity_sixteen_bundle.bundle_checks()
        transition = result["transition"]
        invariants = result["topology_and_characteristics"]

        self.assertEqual(result["components"], ["Np", "Nm"])
        self.assertEqual(transition["representation"], "diag(I_2,Q,Q,Q)")
        self.assertEqual(transition["complex_transition_dimension"], 8)
        self.assertEqual(transition["real_transition_dimension"], 16)
        self.assertTrue(transition["quaternion_basis_homomorphism_real"])
        self.assertTrue(transition["quaternion_basis_homomorphism_complex"])
        self.assertTrue(transition["quaternionic_structures_preserved"])
        self.assertEqual(
            [
                (
                    row["representation"],
                    row["multiplicity"],
                    row["ordinary_bundle_per_copy"],
                    row["reduced_k_class_per_copy"],
                )
                for row in invariants["summands"]
            ],
            [
                ("V_(0,-4)", 1, "C", "0"),
                ("V_(1,-3)", 2, "xi", "x"),
                ("V_(0,-2)", 1, "C", "0"),
                ("V_(1,-1)", 1, "xi", "x"),
            ],
        )
        self.assertEqual(invariants["real_bundle"], "trivial rank 16 by stable-range cancellation")
        self.assertEqual(invariants["quaternionic_triviality"], "nontrivial")

    def test_rank_topology_and_k_theory_mutations_are_rejected(self) -> None:
        rank_mutation = nullity_sixteen_bundle.bundle_checks("drop_standard_doublet")
        topology_mutation = nullity_sixteen_bundle.bundle_checks("change_euler_boundary")
        k_theory_mutation = nullity_sixteen_bundle.bundle_checks("kill_k_theory_torsion")

        self.assertFalse(rank_mutation["pass"])
        self.assertEqual(rank_mutation["transition"]["complex_transition_dimension"], 6)
        self.assertFalse(topology_mutation["pass"])
        self.assertNotEqual(topology_mutation["base_topology"]["integral_cohomology"].get("6"), "Z/2")
        self.assertFalse(k_theory_mutation["pass"])
        self.assertFalse(k_theory_mutation["representation_ring_k_theory"]["generator_nonzero"])


if __name__ == "__main__":
    unittest.main()
