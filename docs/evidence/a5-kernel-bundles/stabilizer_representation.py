"""Exact connected stabilizer representations on the nullity-sixteen fibers.

The compact connected base algebra is generated by the fourteen octonion
derivations and the lifted base phase from ``kernel_symmetry.py``.  At an
``N_+`` or ``N_-`` representative this script solves for the point
stabilizer, restricts its domain action to the real left kernel, and uses
``J = L_(e_16)`` to write the resulting representation on a complex
eight-dimensional fiber.
"""

