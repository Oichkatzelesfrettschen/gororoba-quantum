import kernel_symmetry as symmetry  # noqa: E402

from cd_core import left_mult_matrix_exact  # noqa: E402

DIMENSION = 32
COMPLEX_FIBER_DIMENSION = 8
COMPACT_GENERATOR_COUNT = 15
ORBITS = ("Np", "Nm")

RationalMatrix = symmetry.RationalMatrix


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise RuntimeError(message)


def _sympy_rational(value: Fraction) -> sp.Rational:
    return sp.Rational(value.numerator, value.denominator)


def _fraction(value: sp.Expr) -> Fraction:
    rational = sp.Rational(value)
    return Fraction(int(rational.p), int(rational.q))


def _zero_matrix() -> RationalMatrix:
    return tuple(tuple(Fraction(0) for _ in range(DIMENSION)) for _ in range(DIMENSION))


def _linear_combination(coefficients: Sequence[Fraction], matrices: Sequence[RationalMatrix]) -> RationalMatrix:
    if len(coefficients) != len(matrices):
        raise ValueError("coefficient and matrix counts differ")
    output = [[Fraction(0) for _ in range(DIMENSION)] for _ in range(DIMENSION)]
    for coefficient, matrix in zip(coefficients, matrices, strict=True):
        if coefficient:
            for row_index, row in enumerate(matrix):
                for column_index, entry in enumerate(row):
                    output[row_index][column_index] += coefficient * entry
    return tuple(tuple(row) for row in output)


def _scale_matrix(matrix: RationalMatrix, scalar: Fraction) -> RationalMatrix:
    return tuple(tuple(scalar * entry for entry in row) for row in matrix)


def _matrix_vector(matrix: RationalMatrix, vector: Sequence[Fraction]) -> tuple[Fraction, ...]:
    return symmetry._rational_matrix_vector_product(matrix, vector)


def _flatten(matrix: RationalMatrix) -> tuple[Fraction, ...]:
    return symmetry._flatten_matrix(matrix)


def _independent_vectors(vectors: Sequence[Sequence[Fraction]]) -> tuple[tuple[Fraction, ...], ...]:
    selected: list[tuple[Fraction, ...]] = []
    rank = 0
    for vector in vectors:
        candidate = tuple(vector)
        candidate_rank = symmetry._rank([*selected, candidate])
        if candidate_rank > rank:
            selected.append(candidate)
            rank = candidate_rank
    return tuple(selected)


def _coordinates(columns: Sequence[Sequence[Fraction]], target: Sequence[Fraction]) -> tuple[Fraction, ...]:
    """Solve a full-column-rank rational system exactly."""
    if not columns:
        raise ValueError("coordinate system needs at least one column")
    coordinate_count = len(columns)
    ambient_dimension = len(columns[0])
    if any(len(column) != ambient_dimension for column in columns) or len(target) != ambient_dimension:
        raise ValueError("coordinate vectors have inconsistent dimensions")
    matrix = sp.Matrix(
        ambient_dimension,
        coordinate_count,
        lambda row, column: _sympy_rational(Fraction(columns[column][row])),
    )
    independent_rows = matrix.T.rref()[1]
    if len(independent_rows) != coordinate_count:
        raise ArithmeticError("coordinate columns are linearly dependent")
    square = matrix.extract(independent_rows, range(coordinate_count))
    target_column = sp.Matrix([_sympy_rational(Fraction(target[row])) for row in independent_rows])
    solution = square.inv() * target_column
    residual = matrix * solution - sp.Matrix([_sympy_rational(Fraction(value)) for value in target])
    _require(not any(residual), "target lies outside the claimed coordinate span")
    return tuple(_fraction(value) for value in solution)


def _compact_triples() -> tuple[tuple[str, symmetry.LieTriple], ...]:
    named = symmetry._expected_lie_triples("")
    compact = (*named[:14], named[-1])
    _require(len(compact) == COMPACT_GENERATOR_COUNT, "compact algebra must have fifteen generators")
    return compact


def _representative(orbit: str) -> tuple[Fraction, ...]:
    if orbit not in ORBITS:
        raise ValueError(f"unknown nullity-sixteen orbit {orbit!r}")
    split_point = [Fraction(value) for value in symmetry.regularity.REPS[orbit]]
    return tuple(symmetry.equations.y_from_split(split_point))


def _stabilizer_coefficients(point: Sequence[Fraction]) -> tuple[tuple[Fraction, ...], ...]:
    compact = _compact_triples()
    tangent_columns = [_matrix_vector(triple[0], point) for _name, triple in compact]
    tangent_rows = [
        [tangent_columns[column][row] for column in range(COMPACT_GENERATOR_COUNT)] for row in range(DIMENSION)
    ]
    coefficients = tuple(tuple(row) for row in symmetry.equations.nullspace(tangent_rows))
    _require(len(coefficients) == 4, f"connected compact point stabilizer has dimension {len(coefficients)}, not 4")
    return coefficients


def _adapted_kernel_basis(
    left_matrix: RationalMatrix, complex_structure: RationalMatrix
) -> tuple[tuple[Fraction, ...], ...]:
    kernel_basis = [tuple(vector) for vector in symmetry.equations.nullspace(left_matrix)]
    _require(len(kernel_basis) == 16, f"nullity-sixteen representative has real nullity {len(kernel_basis)}")
    adapted: list[tuple[Fraction, ...]] = []
    for candidate in kernel_basis:
        partner = _matrix_vector(complex_structure, candidate)
        if symmetry._rank([*adapted, candidate, partner]) == len(adapted) + 2:
            adapted.extend((candidate, partner))
    _require(len(adapted) == 16, "J-adapted kernel basis has fewer than sixteen vectors")
    return tuple(adapted)


def _fiber_matrix(
    domain: RationalMatrix,
    adapted_basis: Sequence[Sequence[Fraction]],
    complex_structure: RationalMatrix,
) -> sp.Matrix:
    matrix = sp.zeros(COMPLEX_FIBER_DIMENSION)
    for source_index in range(COMPLEX_FIBER_DIMENSION):
        source = adapted_basis[2 * source_index]
        partner = adapted_basis[2 * source_index + 1]
        image = _matrix_vector(domain, source)
        partner_image = _matrix_vector(domain, partner)
        coordinates = _coordinates(adapted_basis, image)
        expected_partner_image = _matrix_vector(complex_structure, image)
        _require(partner_image == expected_partner_image, "stabilizer action fails to commute with J on the kernel")
        for target_index in range(COMPLEX_FIBER_DIMENSION):
            real_coefficient = coordinates[2 * target_index]
            imaginary_coefficient = coordinates[2 * target_index + 1]
            matrix[target_index, source_index] = _sympy_rational(real_coefficient) + sp.I * _sympy_rational(
                imaginary_coefficient
            )
    return matrix


def _center_coefficients(stabilizer_domains: Sequence[RationalMatrix]) -> tuple[Fraction, ...]:
    rows: list[list[Fraction]] = []
    for fixed in stabilizer_domains:
        commutators = [symmetry._matrix_commutator(candidate, fixed) for candidate in stabilizer_domains]
        for coordinate in range(DIMENSION * DIMENSION):
            rows.append([_flatten(commutator)[coordinate] for commutator in commutators])
    center = symmetry.equations.nullspace(rows)
    _require(len(center) == 1, f"connected point stabilizer center has dimension {len(center)}, not 1")
    return tuple(center[0])


def _primitive_integer_vector(values: Sequence[Fraction]) -> tuple[int, ...]:
    denominator_lcm = math.lcm(*(value.denominator for value in values))
    integers = [int(value * denominator_lcm) for value in values]
    divisor = math.gcd(*integers)
    if divisor:
        integers = [value // abs(divisor) for value in integers]
    first_nonzero = next((value for value in integers if value), 0)
    if first_nonzero < 0:
        integers = [-value for value in integers]
    return tuple(integers)


def _derived_basis(stabilizer_domains: Sequence[RationalMatrix]) -> tuple[RationalMatrix, ...]:
    commutators = [
        symmetry._matrix_commutator(stabilizer_domains[first], stabilizer_domains[second])
        for first in range(len(stabilizer_domains))
        for second in range(first + 1, len(stabilizer_domains))
    ]
    independent = _independent_vectors([_flatten(matrix) for matrix in commutators])
    _require(len(independent) == 3, f"derived stabilizer algebra has dimension {len(independent)}, not 3")
    return tuple(
        tuple(tuple(vector[row * DIMENSION + column] for column in range(DIMENSION)) for row in range(DIMENSION))
        for vector in independent
    )


def _killing_matrix(derived_domains: Sequence[RationalMatrix]) -> sp.Matrix:
    adjoint: list[sp.Matrix] = []
    flattened = [_flatten(matrix) for matrix in derived_domains]
    for left in derived_domains:
        columns = [
            _coordinates(flattened, _flatten(symmetry._matrix_commutator(left, right))) for right in derived_domains
        ]
        adjoint.append(
            sp.Matrix(
                len(derived_domains),
                len(derived_domains),
                lambda row, column, coordinates=columns: _sympy_rational(coordinates[column][row]),
            )
        )
    return sp.Matrix(
        len(derived_domains),
        len(derived_domains),
        lambda row, column: sp.trace(adjoint[row] * adjoint[column]),
    )


def _casimir(
    derived_domains: Sequence[RationalMatrix],
    adapted_basis: Sequence[Sequence[Fraction]],
    complex_structure: RationalMatrix,
) -> sp.Matrix:
    representation = [_fiber_matrix(matrix, adapted_basis, complex_structure) for matrix in derived_domains]
    killing_inverse = _killing_matrix(derived_domains).inv()
    casimir = sp.zeros(COMPLEX_FIBER_DIMENSION)
    for row, left in enumerate(representation):
        for column, right in enumerate(representation):
            casimir += killing_inverse[row, column] * left * right
    return sp.simplify(casimir)


def _highest_weight(casimir_eigenvalue: sp.Expr) -> int:
    for highest_weight in range(COMPLEX_FIBER_DIMENSION):
        expected = sp.Rational(highest_weight * (highest_weight + 2), 8)
        if sp.simplify(casimir_eigenvalue - expected) == 0:
            return highest_weight
    raise ArithmeticError(f"unrecognized sl2 Casimir eigenvalue {casimir_eigenvalue}")


def _joint_decomposition(center: sp.Matrix, casimir: sp.Matrix) -> list[dict[str, Any]]:
    center_eigenvalues = center.eigenvals()
    casimir_eigenvalues = casimir.eigenvals()
    rows: list[dict[str, Any]] = []
    identity = sp.eye(COMPLEX_FIBER_DIMENSION)
    for center_weight in sorted(center_eigenvalues, key=sp.default_sort_key):
        for casimir_eigenvalue in sorted(casimir_eigenvalues, key=sp.default_sort_key):
            stacked = (center - center_weight * identity).col_join(casimir - casimir_eigenvalue * identity)
            joint_dimension = COMPLEX_FIBER_DIMENSION - stacked.rank()
            if joint_dimension == 0:
                continue
            highest_weight = _highest_weight(casimir_eigenvalue)
            irreducible_dimension = highest_weight + 1
            if joint_dimension % irreducible_dimension:
                raise ArithmeticError("joint eigenspace dimension is not a sum of equal sl2 irreducibles")
            rows.append(
                {
                    "central_weight": sp.sstr(center_weight),
                    "sl2_highest_weight": highest_weight,
                    "irreducible_dimension": irreducible_dimension,
                    "multiplicity": joint_dimension // irreducible_dimension,
                    "joint_dimension": joint_dimension,
                    "casimir_eigenvalue": sp.sstr(casimir_eigenvalue),
                }
            )
    return rows


def _commutant_basis(representation: Sequence[sp.Matrix]) -> list[sp.Matrix]:
    """Return the exact complex commutant of the represented stabilizer algebra."""
    rows: list[list[sp.Expr]] = []
    for generator in representation:
        for row_index in range(COMPLEX_FIBER_DIMENSION):
            for column_index in range(COMPLEX_FIBER_DIMENSION):
                row = [sp.Integer(0)] * (COMPLEX_FIBER_DIMENSION * COMPLEX_FIBER_DIMENSION)
                for middle_index in range(COMPLEX_FIBER_DIMENSION):
                    row[row_index * COMPLEX_FIBER_DIMENSION + middle_index] += generator[middle_index, column_index]
                    row[middle_index * COMPLEX_FIBER_DIMENSION + column_index] -= generator[row_index, middle_index]
                rows.append(row)
    nullspace = sp.Matrix(rows).nullspace()
    return [
        sp.Matrix(
            COMPLEX_FIBER_DIMENSION,
            COMPLEX_FIBER_DIMENSION,
            lambda row, column, entries=vector: entries[row * COMPLEX_FIBER_DIMENSION + column],
        )
        for vector in nullspace
    ]


def _spectral_projector(matrix: sp.Matrix, eigenvalue: sp.Expr) -> sp.Matrix:
    eigenvalues = list(matrix.eigenvals())
    projector = sp.eye(COMPLEX_FIBER_DIMENSION)
    for other in eigenvalues:
        if other != eigenvalue:
            projector = projector * (matrix - other * sp.eye(COMPLEX_FIBER_DIMENSION)) / (eigenvalue - other)
    return sp.simplify(projector)


def _multiplicity_projectors(
    representation: Sequence[sp.Matrix], center: sp.Matrix, repeated_weight: sp.Expr
) -> tuple[list[sp.Matrix], int]:
    """Split the repeated doublet isotypic block with an exact commutant element."""
    weight_projector = _spectral_projector(center, repeated_weight)
    _require(weight_projector.rank() == 4, "repeated central-weight block must have dimension four")
    commutant = _commutant_basis(representation)
    block_basis = sp.Matrix.hstack(*weight_projector.columnspace())
    candidates = [*commutant]
    candidates.extend(
        commutant[first] + commutant[second]
        for first in range(len(commutant))
        for second in range(first + 1, len(commutant))
    )
    splitting_matrix: sp.Matrix | None = None
    splitting_eigenvalues: list[sp.Expr] = []
    for candidate in candidates:
        restricted, parameters = block_basis.gauss_jordan_solve(candidate * block_basis)
        _require(parameters.rows == 0, "commutant element escaped the repeated isotypic block")
        eigenvalues = list(restricted.eigenvals())
        if len(eigenvalues) == 2 and all(restricted.eigenvals()[value] == 2 for value in eigenvalues):
            splitting_matrix = sp.simplify(weight_projector * candidate * weight_projector)
            splitting_eigenvalues = eigenvalues
            break
    _require(splitting_matrix is not None, "commutant supplies no exact two-plus-two split")
    first_eigenvalue, second_eigenvalue = splitting_eigenvalues
    first = sp.simplify(
        weight_projector
        * (splitting_matrix - second_eigenvalue * weight_projector)
        / (first_eigenvalue - second_eigenvalue)
    )
    second = sp.simplify(weight_projector - first)
    return [first, second], len(commutant)


def _projector_certificate(
    representation: Sequence[sp.Matrix], center: sp.Matrix, decomposition: Sequence[dict[str, Any]]
) -> dict[str, Any]:
    center_weights = [sp.sympify(row["central_weight"]) for row in decomposition]
    projectors: list[tuple[str, sp.Matrix]] = []
    commutant_dimension = 0
    for weight in center_weights:
        central_projector = _spectral_projector(center, weight)
        matching = next(row for row in decomposition if sp.sympify(row["central_weight"]) == weight)
        if matching["multiplicity"] == 1:
            projectors.append((sp.sstr(weight), central_projector))
        else:
            split, commutant_dimension = _multiplicity_projectors(representation, center, weight)
            projectors.extend((sp.sstr(weight), projector) for projector in split)
    identity = sp.eye(COMPLEX_FIBER_DIMENSION)
    idempotent = all(
        sp.simplify(projector * projector - projector) == sp.zeros(COMPLEX_FIBER_DIMENSION)
        for _, projector in projectors
    )
    invariant = all(
        sp.simplify(projector * generator - generator * projector) == sp.zeros(COMPLEX_FIBER_DIMENSION)
        for _, projector in projectors
        for generator in representation
    )
    orthogonal = all(
        sp.simplify(projectors[first][1] * projectors[second][1]) == sp.zeros(COMPLEX_FIBER_DIMENSION)
        for first in range(len(projectors))
        for second in range(len(projectors))
        if first != second
    )
    complete = sp.simplify(
        sum((projector for _, projector in projectors), sp.zeros(COMPLEX_FIBER_DIMENSION)) - identity
    ) == sp.zeros(COMPLEX_FIBER_DIMENSION)
    return {
        "commutant_dimension": commutant_dimension,
        "projector_count": len(projectors),
        "projector_weights": [weight for weight, _projector in projectors],
        "projector_ranks": [projector.rank() for _weight, projector in projectors],
        "all_idempotent": idempotent,
        "all_invariant": invariant,
        "pairwise_annihilating": orthogonal,
        "sum_to_identity": complete,
        "pass": idempotent and invariant and orthogonal and complete,
    }


def _connected_group_certificate(
    primitive_center: Sequence[int],
    compact: Sequence[tuple[str, symmetry.LieTriple]],
    point: Sequence[Fraction],
    derived_domains: Sequence[RationalMatrix],
) -> dict[str, Any]:
    """Certify the diagonal Z2 relation in SU(2) x U(1)."""
    identity = symmetry._identity_matrix()
    base_identity = symmetry._restrict_base_matrix(identity)
    g2_coefficients = [Fraction(value) for value in primitive_center]
    g2_coefficients[-1] = Fraction(0)
    base_matrices = [triple[0] for _name, triple in compact]
    domain_matrices = [triple[1] for _name, triple in compact]
    g2_base = _linear_combination(g2_coefficients, base_matrices)
    g2_domain = _linear_combination(g2_coefficients, domain_matrices)
    phase_base = base_matrices[-1]
    phase_domain = domain_matrices[-1]

    g2_base_square = symmetry._matrix_product(g2_base, g2_base)
    g2_domain_square = symmetry._matrix_product(g2_domain, g2_domain)
    g2_base_cubic = symmetry._matrix_product(g2_base_square, g2_base)
    g2_domain_cubic = symmetry._matrix_product(g2_domain_square, g2_domain)
    g2_base_fourth = symmetry._matrix_product(g2_base_square, g2_base_square)
    g2_domain_fourth = symmetry._matrix_product(g2_domain_square, g2_domain_square)
    g2_base_fifth = symmetry._matrix_product(g2_base_fourth, g2_base)
    g2_domain_fifth = symmetry._matrix_product(g2_domain_fourth, g2_domain)
    base_minimal_relation = (
        symmetry._matrix_add(
            symmetry._matrix_add(g2_base_fifth, symmetry._matrix_scale(g2_base_cubic, 5)),
            symmetry._matrix_scale(g2_base, 4),
        )
        == _zero_matrix()
    )
    domain_minimal_relation = (
        symmetry._matrix_add(
            symmetry._matrix_add(g2_domain_fifth, symmetry._matrix_scale(g2_domain_cubic, 5)),
            symmetry._matrix_scale(g2_domain, 4),
        )
        == _zero_matrix()
    )
    base_half_turn = symmetry._matrix_add(
        symmetry._matrix_add(identity, _scale_matrix(g2_base_square, Fraction(8, 3))),
        _scale_matrix(g2_base_fourth, Fraction(2, 3)),
    )
    domain_half_turn = symmetry._matrix_add(
        symmetry._matrix_add(identity, _scale_matrix(g2_domain_square, Fraction(8, 3))),
        _scale_matrix(g2_domain_fourth, Fraction(2, 3)),
    )
    base_half_turn_involutive = symmetry._matrix_product(base_half_turn, base_half_turn) == identity
    domain_half_turn_involutive = symmetry._matrix_product(domain_half_turn, domain_half_turn) == identity
    half_turn_nonidentity = base_half_turn != identity and domain_half_turn != identity
    half_turn_fixes_point = _matrix_vector(base_half_turn, point) == tuple(point)
    half_turn_centralizes_su2 = all(
        symmetry._matrix_commutator(domain_half_turn, generator) == _zero_matrix() for generator in derived_domains
    )
    phase_base_is_complex_structure = symmetry._matrix_product(phase_base, phase_base) == symmetry._matrix_scale(
        base_identity, -1
    )
    phase_domain_is_complex_structure = symmetry._matrix_product(phase_domain, phase_domain) == symmetry._matrix_scale(
        identity, -1
    )
    factors_commute = symmetry._matrix_commutator(g2_domain, phase_domain) == _zero_matrix()
    relation_pass = (
        primitive_center[-1] == 2
        and base_minimal_relation
        and domain_minimal_relation
        and base_half_turn_involutive
        and domain_half_turn_involutive
        and half_turn_nonidentity
        and half_turn_fixes_point
        and half_turn_centralizes_su2
        and phase_base_is_complex_structure
        and phase_domain_is_complex_structure
        and factors_commute
    )
    return {
        "g2_base_characteristic_polynomial": sp.sstr(sp.factor(sp.Matrix(g2_base).charpoly().as_expr())),
        "g2_domain_characteristic_polynomial": sp.sstr(sp.factor(sp.Matrix(g2_domain).charpoly().as_expr())),
        "primitive_phase_coefficient": primitive_center[-1],
        "g2_center_generator_satisfies_x_x2_plus_1_x2_plus_4": base_minimal_relation and domain_minimal_relation,
        "phase_generators_square_to_minus_identity": phase_base_is_complex_structure
        and phase_domain_is_complex_structure,
        "g2_and_phase_generators_commute": factors_commute,
        "central_half_turn_is_nonidentity_involution": base_half_turn_involutive
        and domain_half_turn_involutive
        and half_turn_nonidentity,
        "central_half_turn_fixes_representative": half_turn_fixes_point,
        "central_half_turn_centralizes_su2": half_turn_centralizes_su2,
        "connected_stabilizer_group": "U(2) = (SU(2) x U(1))/diagonal Z_2",
        "pass": relation_pass,
    }


def _orbit_check(orbit: str, mutation: str = "") -> dict[str, Any]:
    point = _representative(orbit)
    compact = _compact_triples()
    stabilizer_coefficients = list(_stabilizer_coefficients(point))
    if mutation == "include_moving_direction":
        moving_index = next(
            index for index, (_name, triple) in enumerate(compact) if any(_matrix_vector(triple[0], point))
        )
        stabilizer_coefficients[0] = tuple(Fraction(index == moving_index) for index in range(COMPACT_GENERATOR_COUNT))
    elif mutation:
        raise ValueError(f"unknown mutation {mutation!r}")

    base_matrices = [triple[0] for _name, triple in compact]
    domain_matrices = [triple[1] for _name, triple in compact]
    stabilizer_bases = [_linear_combination(coefficients, base_matrices) for coefficients in stabilizer_coefficients]
    stabilizer_domains = [
        _linear_combination(coefficients, domain_matrices) for coefficients in stabilizer_coefficients
    ]
    point_fixed = [not any(_matrix_vector(matrix, point)) for matrix in stabilizer_bases]
    if mutation:
        return {
            "orbit": orbit,
            "mutation": mutation,
            "stabilizer_dimension": len(stabilizer_coefficients),
            "point_fixed": point_fixed,
            "pass": all(point_fixed),
        }

    y = tuple(point)
    left_matrix = tuple(tuple(row) for row in left_mult_matrix_exact(DIMENSION, y))
    complex_structure_vector = [Fraction(0)] * DIMENSION
    complex_structure_vector[DIMENSION // 2] = Fraction(1)
    complex_structure = tuple(tuple(row) for row in left_mult_matrix_exact(DIMENSION, complex_structure_vector))
    adapted_basis = _adapted_kernel_basis(left_matrix, complex_structure)
    kernel_preserved = [
        all(not any(_matrix_vector(left_matrix, _matrix_vector(domain, vector))) for vector in adapted_basis)
        for domain in stabilizer_domains
    ]
    fiber_matrices = [_fiber_matrix(domain, adapted_basis, complex_structure) for domain in stabilizer_domains]
    center_coefficients = _center_coefficients(stabilizer_domains)
    center_domain = _linear_combination(center_coefficients, stabilizer_domains)
    center_fiber = _fiber_matrix(center_domain, adapted_basis, complex_structure)
    compact_center_coefficients = tuple(
        sum(
            (center_coefficients[row] * stabilizer_coefficients[row][column] for row in range(4)),
            Fraction(0),
        )
        for column in range(COMPACT_GENERATOR_COUNT)
    )
    primitive_center = _primitive_integer_vector(compact_center_coefficients)
    compact_names = [name for name, _triple in compact]
    primitive_scale = next(
        Fraction(primitive, original)
        for primitive, original in zip(primitive_center, compact_center_coefficients, strict=True)
        if original
    )
    primitive_center_fiber = sp.simplify(_sympy_rational(primitive_scale) * center_fiber)
    derived_domains = _derived_basis(stabilizer_domains)
    killing = _killing_matrix(derived_domains)
    casimir = _casimir(derived_domains, adapted_basis, complex_structure)
    decomposition = _joint_decomposition(primitive_center_fiber, casimir)
    projector_certificate = _projector_certificate(fiber_matrices, primitive_center_fiber, decomposition)
    quotient_parity = all(
        (int(sp.im(sp.sympify(row["central_weight"]))) - row["sl2_highest_weight"]) % 2 == 0 for row in decomposition
    )
    representation_commutators_match = all(
        sp.simplify(
            fiber_matrices[first] * fiber_matrices[second]
            - fiber_matrices[second] * fiber_matrices[first]
            - _fiber_matrix(
                symmetry._matrix_commutator(stabilizer_domains[first], stabilizer_domains[second]),
                adapted_basis,
                complex_structure,
            )
        )
        == sp.zeros(COMPLEX_FIBER_DIMENSION)
        for first in range(4)
        for second in range(first + 1, 4)
    )
    connected_group = _connected_group_certificate(primitive_center, compact, point, derived_domains)
    derived_killing_eigenvalues = {sp.sstr(value): multiplicity for value, multiplicity in killing.eigenvals().items()}
    return {
        "orbit": orbit,
        "mutation": mutation,
        "compact_algebra_dimension": COMPACT_GENERATOR_COUNT,
        "compact_orbit_dimension": COMPACT_GENERATOR_COUNT - len(stabilizer_coefficients),
        "stabilizer_dimension": len(stabilizer_coefficients),
        "stabilizer_center_dimension": 1,
        "stabilizer_derived_dimension": len(derived_domains),
        "stabilizer_lie_algebra": "su(2) + u(1)",
        "connected_stabilizer_group": connected_group,
        "point_fixed": point_fixed,
        "kernel_preserved": kernel_preserved,
        "complex_fiber_dimension": COMPLEX_FIBER_DIMENSION,
        "representation_commutators_match": representation_commutators_match,
        "compact_domain_matrices_skew_symmetric": all(
            sp.Matrix(matrix) + sp.Matrix(matrix).T == sp.zeros(DIMENSION) for matrix in stabilizer_domains
        ),
        "primitive_center_coefficients_in_compact_basis": list(primitive_center),
        "primitive_center_named_coefficients": {
            name: coefficient for name, coefficient in zip(compact_names, primitive_center, strict=True) if coefficient
        },
        "center_characteristic_polynomial": sp.sstr(primitive_center_fiber.charpoly().as_expr()),
        "derived_killing_determinant": sp.sstr(sp.factor(killing.det())),
        "derived_killing_eigenvalues": derived_killing_eigenvalues,
        "casimir_characteristic_polynomial": sp.sstr(sp.factor(casimir.charpoly().as_expr())),
        "irreducible_decomposition": decomposition,
        "su2_restriction": {"trivial_lines": 2, "standard_doublets": 3},
        "weights_descend_to_su2_times_u1_mod_diagonal_z2": quotient_parity,
        "invariant_projectors": projector_certificate,
        "pass": all(point_fixed)
        and all(kernel_preserved)
        and representation_commutators_match
        and projector_certificate["pass"]
        and connected_group["pass"]
        and len(derived_domains) == 3
        and killing.det() != 0
        and sum(row["joint_dimension"] for row in decomposition) == COMPLEX_FIBER_DIMENSION,
    }


def _orbit_task(item: tuple[str, str]) -> dict[str, Any]:
    orbit, mutation = item
    return _orbit_check(orbit, mutation)


def stabilizer_checks(mutation: str = "") -> dict[str, Any]:
    """Compute the connected compact stabilizer and its complex fiber representation."""
    if mutation not in ("", "include_moving_direction"):
        raise ValueError(f"unknown mutation {mutation!r}")
    rows = symmetry.parallel.ordered_map(_orbit_task, [(orbit, mutation) for orbit in ORBITS], min_items=1)
    equivalent_decompositions = (
        mutation == "" and rows[0]["irreducible_decomposition"] == rows[1]["irreducible_decomposition"]
    )
    return {
        "mutation": mutation,
        "rows": rows,
        "equivalent_decompositions": equivalent_decompositions,
        "pass": all(row["pass"] for row in rows) and (equivalent_decompositions if mutation == "" else False),
    }


def build_result() -> dict[str, Any]:
    result = stabilizer_checks()
    return {
        "schema": "a5-nullity-sixteen-stabilizer-representation-v1",
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "stabilizer_representation": result,
        "pass": result["pass"],
    }


def _self_test_mutation_task(mutation: str) -> dict[str, Any]:
    """Build one independent stabilizer mutation for the parent self-test."""
    return stabilizer_checks(mutation)


def self_test() -> None:
    baseline = stabilizer_checks()
    if not baseline["pass"]:
        raise RuntimeError("baseline stabilizer representation check failed")
    mutation = symmetry.parallel.ordered_map(
        _self_test_mutation_task,
        ["include_moving_direction"],
        min_items=1,
    )[0]
    if mutation["pass"] or all(all(row["point_fixed"]) for row in mutation["rows"]):
        raise RuntimeError("moving-direction mutation survived the stabilizer check")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--check", type=Path)
    parser.add_argument("--self-test", action="store_true")
    arguments = parser.parse_args()
    if arguments.check is not None and (arguments.self_test or arguments.out is not None):
        parser.error("--check cannot be combined with --self-test or --out")
    if arguments.self_test:
        self_test()
        print("PASS: nullity-sixteen stabilizer representation self-test")
    if arguments.out is not None or arguments.check is not None:
        result = build_result()
        payload = (json.dumps(result, indent=2, sort_keys=True) + "\n").encode()
        if arguments.check is not None:
            if payload != arguments.check.read_bytes():
                raise SystemExit(
                    f"stabilizer_representation.py: fresh JSON differs byte-for-byte from {arguments.check}"
                )
            print(f"stabilizer_representation.py: fresh JSON matches {arguments.check}")
        else:
            arguments.out.write_bytes(payload)
            print(f"wrote {arguments.out}")
    if not arguments.self_test and arguments.out is None and arguments.check is None:
        parser.error("choose --self-test, --out, or --check")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
