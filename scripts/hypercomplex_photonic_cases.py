"""Build full-output photonic pilots and ordered repeat blocks without submitting jobs.

The static readiness computation isolates the payload class from the failed
Ascella iterators. A successful readiness acquisition remains a prerequisite,
rather than evidence that an iterator or a different device works.
"""

