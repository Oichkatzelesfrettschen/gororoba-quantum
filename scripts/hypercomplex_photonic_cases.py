FROZEN_INVENTORY_SHA256 = "8918c58f0c1b82849078257a831e2f2d210165c66709f3f7cca12ba3a69de452"


def _check_frozen_file(arguments: tuple[str, str, str]) -> None:
    directory, name, digest = arguments
    if hashlib.sha256((Path(directory) / name).read_bytes()).hexdigest() != digest:
        raise ValueError(f"frozen identity differs: {name}")


def check_frozen_identity(directory: Path) -> None:
    """Bind the exact retained file set and bytes independently of numerical synthesis."""
    inventory = directory / "frozen-file-sha256.json"
    if hashlib.sha256(inventory.read_bytes()).hexdigest() != FROZEN_INVENTORY_SHA256:
        raise ValueError("frozen identity inventory differs from the reviewed SHA-256")
    expected = json.loads(inventory.read_bytes())
    actual = {path.relative_to(directory).as_posix() for path in directory.rglob("*.json") if path != inventory}
    if actual != set(expected):
        raise ValueError("frozen identity file set differs from the reviewed inventory")
    ordered_map(_check_frozen_file, [(str(directory), name, digest) for name, digest in expected.items()], min_items=1)


def _campaign_file(arguments: tuple[str, str, str]) -> None:
    directory, name, expected = arguments
    retained = json.loads((Path(directory) / name).read_bytes())
    fresh = json.loads(expected)
    if not name.endswith("/cases.json"):
        if retained != fresh:
            raise ValueError(f"campaign metadata differs: {name}")
        return
    import qd_platform
    from bdsc_certificate import close

    circuit = qd_platform.load_case(Path(directory) / Path(name).parent)[1]
    qd_platform.template_experiment(retained, circuit)
    # The hash inventory protects the angles exactly; full-operator reconstruction
    # checks their meaning. Numerical synthesis may choose another phase branch.
    for manifest in (retained, fresh):
        manifest["circuit"].pop("sha256")
        for setting in manifest["settings"]:
            setting.pop("circuit_params")
    try:
        close(retained, fresh, name)
    except ValueError as error:
        raise ValueError(f"campaign metadata differs: {error}") from error


def check_campaign_files(directory: Path, files: dict[str, str]) -> None:
    """Check metadata and the entire frozen optical operator, without resynthesizing its identity."""
    ordered_map(_campaign_file, [(str(directory), name, value) for name, value in files.items()], min_items=1)


def _check_file(arguments: tuple[str, str, str]) -> None:
    directory, name, expected = arguments
    if (Path(directory) / name).read_bytes() != expected.encode("utf-8"):
        raise ValueError(f"retained {name} bytes differ from the regenerated case")


def check_files(directory: Path, files: dict[str, str]) -> None:
    """Compare regenerated bytes, including every manifest and bound circuit digest."""
    ordered_map(_check_file, [(str(directory), name, value) for name, value in files.items()], min_items=1)


def characterization_frontier() -> dict[str, Any]:
    """Enumerate declared finite controls without claiming readiness or a runtime packing model."""
    catalogue_path = Path(__file__).resolve().parents[1] / "docs/evidence/quandela/catalogue.json"
    catalogue = json.loads(catalogue_path.read_bytes())
    specs = catalogue["processors"]["qpu:ascella"]["specs"]
    modes = specs["constraints"]["max_mode_count"]
    sources = specs["connected_input_modes"]
    photon_limit = specs["constraints"]["max_photon_count"]
    if modes != 12 or sources != [0, 2, 4, 6, 8, 10] or photon_limit != 6:
        raise ValueError("the declared Ascella frontier requires qualification against changed device constraints")
    state = "awaiting-instrument-and-timing-admission"
    rows = [
        {
            "name": f"source-{source}-output-{output}",
            "source": source,
            "output": output,
            "mechanism": "transfer",
            "state": state,
        }
        for source in sources
        for output in range(modes)
    ]
    rows.extend(
        {
            "name": f"source-{source}-pair-{first}-{second}-quadrature-{quadrature}",
            "source": source,
            "outputs": [first, second],
            "quadrature_index": quadrature,
            "phase_radians": quadrature * math.pi / 2,
            "mechanism": "recombined-phase",
            "state": state,
        }
        for source in sources
        for first, second in itertools.combinations(range(modes), 2)
        for quadrature in range(4)
    )
    subsets = [
        list(subset) for count in range(1, photon_limit + 1) for subset in itertools.combinations(sources, count)
    ]
    surface = {"modes": modes, "sources": sources, "photon_limit": photon_limit, "detector": specs["detector"]}
    return {
        "schema": "ascella-finite-capability-frontier-v1",
        "source": "docs/evidence/quandela/catalogue.json",
        "constraint_surface": surface,
        "constraint_surface_sha256": hashlib.sha256(json.dumps(surface, sort_keys=True).encode()).hexdigest(),
        "modes": modes,
        "connected_inputs": sources,
        "photon_limit": photon_limit,
        "settings": rows,
        "nonempty_connected_source_subsets": subsets,
        "six_photon_fock_outputs": math.comb(modes + photon_limit - 1, photon_limit),
        "threshold_patterns_with_one_through_six_clicks": sum(math.comb(modes, count) for count in range(1, 7)),
        "maximum_job_seconds": 300,
        "packing": "await a measured Ascella per-setting overhead and rate before selecting pack sizes",
        "boundary": "finite declared controls, not all continuous circuits, qualified tomography or acquired data",
    }


def documents(manifest: dict[str, Any], circuit: dict[str, Any]) -> dict[str, str]:
    text = json.dumps(circuit, indent=1) + "\n"
    manifest["circuit"] = {"file": "circuit.json", "sha256": hashlib.sha256(text.encode()).hexdigest()}
    return {"circuit.json": text, "cases.json": json.dumps(manifest, indent=1) + "\n"}


