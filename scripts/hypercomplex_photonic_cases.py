def native_readiness_case(processor: dict[str, Any], all_sources: bool = False) -> dict[str, str]:
    """Bind the published calibrated mesh numerically to test the documented compatible-circuit path."""
    from qd_belenos_mesh import coupler, decode

    specs = processor["specs"]
    if specs["constraints"]["max_mode_count"] != 12 or 0 not in specs["connected_input_modes"]:
        raise ValueError("the native readiness case requires the recorded 12-mode Ascella input zero")
    architecture = decode(specs["architecture"])
    matrix = np.eye(12, dtype=complex)
    operations: list[list[Any]] = []
    parameters: dict[str, float] = {}
    symbols: list[str] = []
    couplers: list[list[Any]] = []
    for kind, mode, value in architecture:
        index = len(parameters)
        if kind == "bs":
            if value[1:] != (0.0, 0.0, 0.0, 0.0):
                raise ValueError("the native readiness builder requires phase-free calibrated Rx couplers")
            operations.append(["BS", mode, index])
            parameters[f"x{index}"] = value[0]
            couplers.append([mode, value[0]])
            matrix[mode : mode + 2] = coupler(*value) @ matrix[mode : mode + 2]
        elif kind == "ps" and isinstance(value, str):
            operations.append(["PS", mode, index])
            parameters[f"x{index}"] = 0.0
            symbols.append(value)
        else:
            raise ValueError("the published native mesh must contain calibrated Rx couplers and symbolic phases")
    input_state = [1] + [0] * 11
    if all_sources:
        input_state = [int(mode in specs["connected_input_modes"]) for mode in range(12)]
        if sum(input_state) != specs["constraints"]["max_photon_count"]:
            raise ValueError("full-source readiness must match the advertised photon limit")
    circuit = {
        "schema": "qd-template-circuit-v1",
        "modes": 12,
        "input_state": input_state,
        "parameters": len(parameters),
        "ops": operations,
        "architecture": {"symbols": symbols, "couplers": couplers},
    }
    manifest = json.loads(readiness_case()["cases.json"])
    manifest.update(
        family="ascella-native-readiness",
        job="static-mesh",
        gate_form="template",
        max_duration=300,
        settings=[
            {
                "name": "calibrated-mesh-zero-phases",
                "compilation_seed": 0,
                "circuit_params": parameters,
                "column": [[float(value.real), float(value.imag)] for value in matrix[:, 0]],
                "operator": {"real": matrix.real.tolist(), "imaginary": matrix.imag.tolist()},
            }
        ],
    )
    manifest["preregistered"] = {
        "primary": "native-compatible static instrument readiness",
        "ideal_probabilities": (np.abs(matrix[:, 0]) ** 2).tolist(),
        "boundary": "tests architecture-compatible submission; does not assume transpilation bypass or recovery",
        "stop": "instrument error or zero samples rejects this native path and stops Ascella submissions",
    }
    if all_sources:
        manifest["job"] = "all-sources"
        manifest["preregistered"] = {
            "primary": "instrument readiness with the full connected-source occupation",
            "boundary": "at-least-one-click filter, including multi-click outputs; not a six-photon coincidence law",
            "stop": "instrument error rejects full-source selection as a remedy; preserve all diagnostics",
        }
    return documents(manifest, circuit)


def _physical_setting(arguments: tuple[dict[str, Any], int, int, int]) -> dict[str, Any]:
    original, repeat, width, logical_modes = arguments
    setting = copy.deepcopy(original)
    setting["name"] = f"{setting['name']}-repeat-{repeat}"
    setting["repeat_index"] = repeat
    setting["column"] += [[0.0, 0.0]] * (width - logical_modes)
    operator = setting["operator"]
    for field in ("real", "imaginary"):
        expanded = np.eye(width) if field == "real" else np.zeros((width, width))
        expanded[:logical_modes, :logical_modes] = operator[field]
        operator[field] = expanded.tolist()
    return setting


def campaign_cases(platform: str, repeats: int = 1) -> dict[str, str]:
    """Full-width circuits with explicit processing and distinct ordered repeat identities.

    The logical operator acts on its original four or eight modes. Identity
    on the remaining modes preserves leakage observations without widening
    the mathematical model or fitting extra phases.
    """
    if platform not in {"ascella", "belenos"} or type(repeats) is not int or not 1 <= repeats <= 3:
        raise ValueError("choose ascella or belenos and one to three repeat blocks")
    if platform == "ascella" and repeats != 1:
        raise ValueError("Ascella admits only the one-block order pilot")
    width = 12 if platform == "ascella" else 24
    families = [("order", order_settings())]
    if platform == "belenos":
        families.extend([("wave", wave_settings()), ("transform", transform_settings())])
    output: dict[str, str] = {}
    for family, settings in families:
        original = qd_cases(settings, family)
        circuit = json.loads(original["circuit.json"])
        logical_modes = circuit["modes"]
        circuit["modes"] = width
        circuit["input_state"] += [0] * (width - logical_modes)
        manifest = json.loads(original["cases.json"])
        compiled = manifest.pop("settings")
        arguments = [(setting, repeat, width, logical_modes) for repeat in range(repeats) for setting in compiled]
        entries = ordered_map(_physical_setting, arguments, min_items=1)
        # At most 24 settings share the documented 180-second execution cap.
        # The cap is a stopping limit; hardware completion time remains measured.
        for offset in range(0, len(entries), 24):
            selected = entries[offset : offset + 24]
            job = f"{family}-repeat-block-{offset // 24}"
            own = {
                **manifest,
                "family": f"{platform}-operators",
                "job": job,
                "platforms": [f"qpu:{platform}"],
                "settings": selected,
                "iterations": len(selected),
                "max_samples": len(selected) * 8192,
                "max_shots": len(selected) * 16384,
                "mitigations": [],
                "logical_modes": logical_modes,
                "output_modes": width,
            }
            own["preregistered"] = {
                **own["preregistered"],
                "primary": "mode frequencies, outside-logical-support counts and matched-repeat differences",
                "loss": "retain shots, physical performance and filter metadata; absolute efficiency uncalibrated",
                "drift": "ordered matched-request differences; recalibration and compiled-mesh equality unestablished",
                "stop": "instrument error, missing iteration, malformed result or zero samples stops this platform",
            }
            output.update({f"{job}/{name}": text for name, text in documents(own, circuit).items()})
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="compare retained cases without writing")
    parser.add_argument("--native-catalogue", type=Path, help="also build a static case from captured Ascella couplers")
    arguments = parser.parse_args()
    if arguments.check:
        check_frozen_identity(arguments.out)
    publish = check_files if arguments.check else write_files
    campaign_publish = check_campaign_files if arguments.check else write_files
    publish(arguments.out / "ascella-readiness", readiness_case())
    campaign_publish(arguments.out / "ascella", campaign_cases("ascella"))
    campaign_publish(arguments.out / "belenos", campaign_cases("belenos", repeats=3))
    frontier = {"frontier.json": json.dumps(characterization_frontier(), indent=1) + "\n"}
    publish(arguments.out / "ascella-capability-frontier", frontier)
    if arguments.native_catalogue:
        catalogue = json.loads(arguments.native_catalogue.read_text())
        publish(
            arguments.out / "ascella-native-readiness", native_readiness_case(catalogue["processors"]["qpu:ascella"])
        )
        publish(
            arguments.out / "ascella-full-source-readiness",
            native_readiness_case(catalogue["processors"]["qpu:ascella"], all_sources=True),
        )
    message = "verified photonic successor cases" if arguments.check else "built photonic cases; submitted zero jobs"
    print(message)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
