"""Serialize cd_sign's complete CPython AST for the Rocq translation validator.

The exporter records ast.iter_fields generically. It does not map Python operations to target-language
constructors: the Rocq certificate checker and independent raw-tree semantics own that interpretation.
The source digest binds the exact UTF-8 bytes of cd_sign and of every top-level definition, assignment or import it
reaches through module-level names, transitively, in source order; edits elsewhere in cd_core.py leave it unchanged,
while a changed or rebound helper changes it. CPython parsing, function selection, name-closure selection,
serialization and source-byte binding remain external trust boundaries.

Usage: "$PYTHON" scripts/cd_sign_source_ast.py [--check | --write]
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "gororoba_quantum"))
from cd_sign_rocq_ast import MUTANT_NEW, MUTANT_OLD  # noqa: E402

import parallel  # noqa: E402

SOURCE = ROOT / "gororoba_quantum" / "cd_core.py"
PROOF = ROOT / "proofs" / "CdSignSourceCertificate.v"
BEGIN = "(* BEGIN source AST: generated by scripts/cd_sign_source_ast.py *)\n"
END = "(* END source AST *)"


class UnsupportedValue(ValueError):
    pass


def string_term(value: str) -> str:
    if all(32 <= ord(char) < 127 for char in value):
        return '"' + value.replace('"', '""') + '"'
    values = " :: ".join(f"{byte}%nat" for byte in value.encode("utf-8"))
    return f"(utf8 ({values} :: nil))"


def list_term(values: list[str], indent: str) -> str:
    return "([" + (";\n" + indent).join(values) + "]%py)"


def raw_term(value: object, indent: str = "") -> str:
    if isinstance(value, ast.AST):
        fields = [
            f"(PField {string_term(name)} {raw_term(item, indent + '  ')})" for name, item in ast.iter_fields(value)
        ]
        return f"(PNode {string_term(type(value).__name__)} {list_term(fields, indent)})"
    if isinstance(value, list):
        return f"(PList {list_term([raw_term(item, indent + '  ') for item in value], indent)})"
    if value is None:
        return "PNone"
    if isinstance(value, bool):
        return "(PBool true)" if value else "(PBool false)"
    if isinstance(value, int):
        return f"(PInt ({value})%Z)"
    if isinstance(value, str):
        return f"(PStr {string_term(value)})"
    raise UnsupportedValue(f"unrepresented AST leaf {type(value).__name__}: {value!r}")


def function_node(source: str, name: str = "cd_sign") -> ast.FunctionDef:
    matches = [node for node in ast.parse(source).body if isinstance(node, ast.FunctionDef) and node.name == name]
    if len(matches) != 1:
        raise UnsupportedValue(f"{len(matches)} top-level definitions of {name}")
    return matches[0]


def _bound_names(node: ast.stmt) -> list[str]:
    if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
        return [node.name]
    if isinstance(node, ast.Import | ast.ImportFrom):
        return [(alias.asname or alias.name).split(".")[0] for alias in node.names]
    if isinstance(node, ast.Assign | ast.AnnAssign | ast.AugAssign):
        targets = node.targets if isinstance(node, ast.Assign) else [node.target]
        return [leaf.id for target in targets for leaf in ast.walk(target) if isinstance(leaf, ast.Name)]
    return []


def closure_source(source: str, name: str = "cd_sign") -> str:
    """Source text of name and of every top-level statement binding a module-level name it reaches, in source order."""
    module = ast.parse(source)
    binders: dict[str, list[ast.stmt]] = {}
    for node in module.body:
        for bound in _bound_names(node):
            binders.setdefault(bound, []).append(node)
    root = function_node(source, name)
    selected: dict[int, ast.stmt] = {}
    pending: list[ast.stmt] = [root]
    while pending:
        node = pending.pop()
        if id(node) in selected:
            continue
        selected[id(node)] = node
        for leaf in ast.walk(node):
            if isinstance(leaf, ast.Name):
                pending.extend(binders.get(leaf.id, []))
    lines = source.splitlines(keepends=True)
    blocks = []
    for node in sorted(selected.values(), key=lambda item: item.lineno):
        decorators = getattr(node, "decorator_list", [])
        start = min([node.lineno] + [item.lineno for item in decorators])
        if node.end_lineno is None:
            raise UnsupportedValue(f"statement at line {node.lineno} has no end line")
        blocks.append("".join(lines[start - 1 : node.end_lineno]))
    return "\n".join(blocks)


def definition(item: tuple[str, str]) -> str:
    name, text = item
    return f"Definition {name} : py :=\n  {raw_term(function_node(text), '  ')}.\n"


def generated(source: str) -> str:
    if source.count(MUTANT_OLD) != 1:
        raise UnsupportedValue("the high-low guard of cd_sign is not unique in the source")
    if source.count("half >>= 1") != 1:
        raise UnsupportedValue("the loop shift of cd_sign is not unique in the source")
    digest = hashlib.sha256(closure_source(source).encode("utf-8")).hexdigest()
    items = [
        ("cd_sign_source", source),
        ("cd_sign_mutant_source", source.replace(MUTANT_OLD, MUTANT_NEW)),
        ("cd_sign_shift_mutant_source", source.replace("half >>= 1", "half >>= 2")),
    ]
    terms = [f'Definition cd_sign_source_sha256 : string := "{digest}".\n']
    return "\n".join(terms + parallel.ordered_map(definition, items))


def span(proof: str) -> tuple[int, int]:
    if proof.count(BEGIN) != 1 or proof.count(END) != 1 or proof.index(BEGIN) > proof.index(END):
        raise UnsupportedValue("source AST markers missing, repeated or out of order")
    return proof.index(BEGIN) + len(BEGIN), proof.index(END)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="compare the complete generated block with the .v file")
    mode.add_argument("--write", action="store_true", help="replace the generated block of the .v file")
    options = parser.parse_args()
    term = generated(SOURCE.read_bytes().decode("utf-8"))
    if not options.check and not options.write:
        sys.stdout.write(term)
        return 0
    proof = PROOF.read_text(encoding="utf-8")
    start, stop = span(proof)
    if options.write:
        PROOF.write_text(proof[:start] + term + proof[stop:], encoding="utf-8")
        return 0
    if proof[start:stop] != term:
        print(f"{PROOF.name}: regenerate the source AST from {SOURCE.name}", file=sys.stderr)
        return 1
    print(f"{PROOF.name}: complete source AST and digest match {SOURCE.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
