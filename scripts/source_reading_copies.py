"""The reading-copy index: every external-only PDF of docs/SOURCES.json with its note, public source and private copy.

docs/SOURCES.json lists under `external_pdfs` each PDF whose rights exclude redistribution; its bytes live in the
ignored `docs/local_source_cache/` and in the owner's private repository gororoba-quantum-documents at
`pdf/<basename of local_cache_path>`, which scripts/fetch_source_cache.py restores from. The index links each entry's
note, its registered `source_url`, and that private path, so the owner opens the copy in one step and every other
reader follows the public source.

Usage:
  "$PYTHON" scripts/source_reading_copies.py [--check]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "docs/SOURCES.json"
OUT = ROOT / "docs/sources/reading-copies.md"
DOCUMENTS = "https://github.com/Oichkatzelesfrettschen/gororoba-quantum-documents/blob/main/pdf/"

HEADER = """# Reading copies of external sources

Generated by [`scripts/source_reading_copies.py`](../../scripts/source_reading_copies.py) from
[`SOURCES.json`](../SOURCES.json); edit the registry and regenerate. Each row names an external-only PDF: its note,
its public source, and its reading copy in the owner's private repository gororoba-quantum-documents. The private
link opens for accounts with access to that repository; every other reader follows the public source, and
[`fetch_source_cache.py`](../../scripts/fetch_source_cache.py) restores the same bytes into the ignored
`docs/local_source_cache/` from either.

| Source | Note | Public source | Private copy |
|---|---|---|---|
"""


def cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def heading(note: Path) -> str:
    """The note's first Markdown heading, the label of an entry that carries no title."""
    for line in note.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def row(entry: dict[str, Any]) -> tuple[str, str]:
    note = Path(entry["note"])
    name = Path(entry["local_cache_path"]).name
    label = cell(entry.get("title") or heading(ROOT / note) or note.stem)
    link = f"[{note.name}](../{note.relative_to('docs').as_posix()})"
    return label.lower(), f"| {label} | {link} | [source]({entry['source_url']}) | [{name}]({DOCUMENTS}{name}) |"


def render() -> str:
    entries = json.loads(SOURCES.read_text(encoding="utf-8"))["external_pdfs"]
    names = [Path(entry["local_cache_path"]).name for entry in entries]
    if len(set(names)) != len(names):
        raise ValueError("two external_pdfs entries share a local_cache_path basename")
    rows = sorted(row(entry) for entry in entries)
    return HEADER + "".join(line + "\n" for _, line in rows)


def main(argv: list[str]) -> int:
    text = render()
    if argv == ["--check"]:
        if OUT.read_text(encoding="utf-8") != text:
            raise ValueError(f"{OUT.relative_to(ROOT)} differs from SOURCES.json; run scripts/source_reading_copies.py")
        return 0
    if argv:
        raise ValueError(f"usage: see the module docstring, not {argv}")
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
