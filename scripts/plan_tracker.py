"""Capture, reconcile and query work plans; rendering never grants execution authority.

Run with an exported PYTHON: "$PYTHON" scripts/plan_tracker.py --help.
"""

from __future__ import annotations

import argparse
import copy
import fcntl
import os
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path
from typing import Any

import plan_records as records
from plan_inventory import check_retained_inventory, git, scan

ROOT = Path(__file__).resolve().parents[1]
INDEX = Path("docs/state/plans.md")
CATALOGUE = Path("docs/state/plan-catalogue.md")
ORDER = {name: position for position, name in enumerate(("active", "paused", "planned", "inbox", "closed"))}


def escaped(value: str) -> str:
    for character in ("\\", "[", "]", "*", "_", "`", "<", ">", "|"):
        value = value.replace(character, "\\" + character)
    return value


def source_link(reference: str) -> str:
    return reference if reference.startswith("https://") else "../../" + reference


def entry(root: Path, plans: dict[str, dict[str, Any]], plan: dict[str, Any]) -> str:
    blocked = records.blockers(plans, plan)
    status = plan["state"] + (f"/{plan['disposition']}" if plan["state"] == "closed" else "")
    next_action = plan.get(
        "next_action", plan.get("resolution", "Triage the question and define its next bounded action.")
    )
    detail = (
        f"Resolution: {escaped(plan['resolution'])}" if plan["state"] == "closed" else f"Next: {escaped(next_action)}"
    )
    if blocked:
        detail += f" Blocked: {escaped('; '.join(blocked))}."
    if records.receipt_freshness(root, plan):
        detail += " Historical receipt inputs changed; revalidation required."
    return (
        f"- **[{plan['id']}](plans/{plan['id']}.json)** ({status}; {plan['reconciliation']['status']}): "
        f"{escaped(plan['summary'])} [Context]({source_link(plan['sources'][0])}).\n  {detail}\n"
    )


def rendered(root: Path, plans: dict[str, dict[str, Any]]) -> dict[Path, str]:
    ordered = sorted(plans.values(), key=lambda plan: (ORDER[plan["state"]], plan["id"]))
    fingerprint = records.digest(plans)
    counts = Counter(plan["state"] for plan in ordered)
    header = (
        "Generated by `scripts/plan_tracker.py render --write`; edit the JSON work records.\n\n"
        f"Source fingerprint: `{fingerprint}`. "
        + ", ".join(f"{counts[state]} {state}" for state in records.STATES)
        + ".\n\nWork completion describes the recorded obligation. Scientific claims and provider execution approvals "
        "retain their own authorities. Historical reports and unresolved findings remain explicit.\n\n"
    )
    focused = [plan for plan in ordered if plan["state"] in {"active", "paused"}]
    index = "# Planning\n\n" + header
    index += "[Complete catalogue](plan-catalogue.md) | [Operator commands](../runbooks/plan-tracker.md)\n\n"
    index += f"## Current focus\n\nShowing {min(12, len(focused))} of {len(focused)} active or paused plans.\n\n"
    index += "\n".join(entry(root, plans, plan) for plan in focused[:12])
    if not focused:
        index += "Select a reconciled item from the catalogue before committing to new work.\n"
    catalogue = "# Complete planning catalogue\n\n" + header
    catalogue += "[Planning entrance](plans.md). Every registered plan appears below.\n\n"
    for state in ("active", "paused", "planned", "inbox", "closed"):
        catalogue += f"## {state.capitalize()}\n\n"
        catalogue += "\n".join(entry(root, plans, plan) for plan in ordered if plan["state"] == state) + "\n"
    return {INDEX: index.rstrip() + "\n", CATALOGUE: catalogue.rstrip() + "\n"}


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(content)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def publish(root: Path, plans: dict[str, dict[str, Any]], plan: dict[str, Any]) -> None:
    candidate = {**plans, plan["id"]: plan}
    records.validate(root, candidate)
    atomic_write(root / records.DIRECTORY / f"{plan['id']}.json", records.encoded(plan))


def read_input(filename: str) -> dict[str, Any]:
    value = records.loads(sys.stdin.read() if filename == "-" else Path(filename).read_text(encoding="utf-8"))
    records.require(isinstance(value, dict), "input must be a JSON object")
    return value


def flatten(value: Any, prefix: str = "") -> dict[str, Any]:
    if isinstance(value, dict):
        result: dict[str, Any] = {}
        for key, member in value.items():
            result.update(flatten(member, f"{prefix}.{key}" if prefix else key))
        return result
    if isinstance(value, list) and value and all(isinstance(item, dict) and "id" in item for item in value):
        return flatten({item["id"]: item for item in value}, prefix)
    return {prefix: value}


def merge_findings(base: dict[str, Any], left: dict[str, Any], right: dict[str, Any]) -> list[dict[str, Any]]:
    findings = []
    for name in sorted(set(base) | set(left) | set(right)):
        before, ours, theirs = (flatten(tree.get(name)) for tree in (base, left, right))
        fields = set(before) | set(ours) | set(theirs)
        left_changed = {field for field in fields if before.get(field) != ours.get(field)}
        right_changed = {field for field in fields if before.get(field) != theirs.get(field)}
        if left_changed and right_changed and left.get(name) != right.get(name):
            findings.append(
                {
                    "plan": name,
                    "left_fields": sorted(left_changed),
                    "right_fields": sorted(right_changed),
                    "overlap": sorted(left_changed & right_changed),
                    "action": "Reconcile ownership, scope, dependencies and receipts before rendering.",
                }
            )
    return findings


def tree_records(root: Path, revision: str) -> dict[str, Any]:
    commit = git(root, "rev-parse", "--verify", f"{revision}^{{commit}}")
    names = git(root, "ls-tree", "-r", "--name-only", commit, str(records.DIRECTORY)).splitlines()
    return {
        Path(name).stem: records.loads(git(root, "show", f"{commit}:{name}"))
        for name in names
        if name.endswith(".json")
    }


def parser() -> argparse.ArgumentParser:
    command = argparse.ArgumentParser(description=__doc__)
    command.add_argument("--root", type=Path, default=ROOT)
    actions = command.add_subparsers(dest="command", required=True)
    for name in ("list", "search"):
        query = actions.add_parser(name)
        if name == "search":
            query.add_argument("query")
        query.add_argument("--state", choices=records.STATES)
        query.add_argument("--kind", choices=records.KINDS)
        query.add_argument("--owner")
        query.add_argument("--blocked", action="store_true")
        query.add_argument("--limit", type=int, default=12)
        query.add_argument("--json", action="store_true")
    show = actions.add_parser("show")
    show.add_argument("id")
    show.add_argument("--json", action="store_true")
    capture = actions.add_parser("capture")
    capture.add_argument("id")
    capture.add_argument("--summary", required=True)
    capture.add_argument("--source", action="append", required=True)
    capture.add_argument("--kind", choices=records.KINDS, default="investigation")
    update = actions.add_parser("update")
    update.add_argument("id")
    update.add_argument("--input", help="JSON object patch; - reads stdin")
    for field in ("summary", "scope", "owner", "next-action", "state"):
        update.add_argument("--" + field)
    step = actions.add_parser("step")
    step.add_argument("id")
    step.add_argument("step_id")
    step.add_argument("--input", help="JSON step patch; - reads stdin")
    step.add_argument("--state", choices=("todo", "doing", "done", "cancelled"))
    for field in ("action", "acceptance", "reason"):
        step.add_argument("--" + field)
    step.add_argument("--receipt", help="JSON receipt object; scope_sha256 may be omitted and will be filled")
    pause = actions.add_parser("pause")
    pause.add_argument("id")
    for field in ("last-result", "next-action", "resume-when"):
        pause.add_argument("--" + field, required=True)
    resume = actions.add_parser("resume")
    resume.add_argument("id")
    actions.add_parser("check")
    render = actions.add_parser("render")
    render.add_argument("--write", action="store_true")
    inventory = actions.add_parser("scan")
    inventory.add_argument("--all-worktrees", action="store_true")
    merge = actions.add_parser("review-merge")
    for field in ("base", "left", "right"):
        merge.add_argument(field)
    return command


def _run(arguments: argparse.Namespace) -> int:
    root = arguments.root.resolve()
    if arguments.command == "scan":
        print(records.encoded(scan(root, arguments.all_worktrees)), end="")
        return 0
    if arguments.command == "review-merge":
        trees = [tree_records(root, getattr(arguments, side)) for side in ("base", "left", "right")]
        findings = merge_findings(*trees)
        print(
            records.encoded(
                {"base": arguments.base, "left": arguments.left, "right": arguments.right, "findings": findings}
            ),
            end="",
        )
        return int(bool(findings))
    plans = records.load(root)
    records.validate(root, plans)
    if arguments.command in {"check", "render"}:
        check_retained_inventory(root, plans)
        outputs = rendered(root, plans)
        if arguments.command == "render" and arguments.write:
            for path, content in outputs.items():
                atomic_write(root / path, content)
        elif arguments.command == "check":
            for path, content in outputs.items():
                records.require(
                    (root / path).exists() and (root / path).read_text() == content, f"stale generated view: {path}"
                )
        else:
            print(outputs[INDEX], end="")
        print(f"plan tracker: {len(plans)} records; input {git(root, 'rev-parse', 'HEAD')}", file=sys.stderr)
        return 0
    if arguments.command in {"list", "search"}:
        records.require(arguments.limit > 0, "limit must be positive")
        selected = []
        for plan in sorted(plans.values(), key=lambda item: (ORDER[item["state"]], item["id"])):
            if any(
                getattr(arguments, key) and plan.get(key) != getattr(arguments, key)
                for key in ("state", "kind", "owner")
            ):
                continue
            if arguments.blocked and not records.blockers(plans, plan):
                continue
            if arguments.command == "search" and arguments.query.casefold() not in records.encoded(plan).casefold():
                continue
            selected.append(plan)
        result = {
            "revision": git(root, "rev-parse", "HEAD"),
            "total": len(selected),
            "shown": min(len(selected), arguments.limit),
            "plans": selected[: arguments.limit],
        }
        if arguments.json:
            print(records.encoded(result), end="")
        else:
            print(f"Input {result['revision']}; showing {result['shown']} of {result['total']}")
            print("\n".join(entry(root, plans, plan) for plan in selected[: arguments.limit]))
        return 0
    if arguments.command == "show":
        records.require(arguments.id in plans, f"unknown plan: {arguments.id}")
        plan = plans[arguments.id]
        if arguments.json:
            print(records.encoded(plan), end="")
        else:
            print(entry(root, plans, plan))
            for step in plan.get("steps", []):
                print(f"- {step['id']} [{step['state']}]: {step['action']}\n  Acceptance: {step['acceptance']}")
                for receipt in step.get("receipts", []):
                    print(f"  Observed {receipt['observed_at']} at {receipt['revision']}: {receipt['result']}")
            print(f"Input {git(root, 'rev-parse', 'HEAD')}; scope SHA-256 {records.obligation(plan)}")
        return 0
    if arguments.command == "capture":
        records.require(arguments.id not in plans, "plan already exists")
        plan = {
            "schema": records.SCHEMA,
            "id": arguments.id,
            "kind": arguments.kind,
            "summary": arguments.summary,
            "sources": arguments.source,
            "state": "inbox",
            "reconciliation": {"status": "unresolved", "note": "Captured context; triage and evidence review pending."},
        }
    else:
        records.require(arguments.id in plans, f"unknown plan: {arguments.id}")
        plan = copy.deepcopy(plans[arguments.id])
        if arguments.command == "update":
            patch = read_input(arguments.input) if arguments.input else {}
            records.require(not ({"id", "schema"} & set(patch)), "identity and schema are immutable")
            patch.update(
                {
                    key: getattr(arguments, key)
                    for key in ("summary", "scope", "owner", "next_action", "state")
                    if getattr(arguments, key) is not None
                }
            )
            plan.update(patch)
        elif arguments.command == "step":
            steps = plan.setdefault("steps", [])
            step = next((item for item in steps if item["id"] == arguments.step_id), None)
            if step is None:
                step = {"id": arguments.step_id, "state": "todo"}
                steps.append(step)
            patch = read_input(arguments.input) if arguments.input else {}
            records.require("id" not in patch, "step identity is immutable")
            step.update(patch)
            step.update(
                {
                    key: getattr(arguments, key)
                    for key in ("action", "acceptance", "reason", "state")
                    if getattr(arguments, key) is not None
                }
            )
            if arguments.receipt:
                receipt = read_input(arguments.receipt)
                receipt.setdefault("scope_sha256", records.obligation(plan, step))
                step.setdefault("receipts", []).append(receipt)
        elif arguments.command == "pause":
            records.require(plan["state"] in {"active", "planned", "paused"}, "only committed work can pause")
            plan["state"] = "paused"
            plan["pause"] = {key: getattr(arguments, key) for key in ("last_result", "next_action", "resume_when")}
            plan["next_action"] = arguments.next_action
        elif arguments.command == "resume":
            records.require(plan["state"] == "paused", "only paused work can resume")
            plan["state"] = "active"
            plan["next_action"] = plan.pop("pause")["next_action"]
    publish(root, plans, plan)
    print(f"Updated {plan['id']}; run render --write to regenerate views.")
    return 0


def run(arguments: argparse.Namespace) -> int:
    if arguments.command not in {"capture", "update", "step", "pause", "resume"} and not (
        arguments.command == "render" and arguments.write
    ):
        return _run(arguments)
    lock_path = Path(git(arguments.root, "rev-parse", "--path-format=absolute", "--git-path", "plan-tracker.lock"))
    with lock_path.open("a") as lock:
        fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
        return _run(arguments)


def main() -> int:
    try:
        return run(parser().parse_args())
    except (ValueError, KeyError, TypeError, OSError, subprocess.CalledProcessError) as error:
        print(f"plan tracker: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
