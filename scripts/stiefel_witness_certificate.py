"""Generate and check the Rocq certificate that the A_6 Stiefel witness is not a zero divisor.

The witness is the a6_integer_witness of docs/evidence/moreno_stiefel/nullity.json:
an integer vector v of length 64 whose halves a, b (cd_core doubling, index
32 + k is the second half) are pure, orthogonal and of squared norm 62. Its
left multiplication L_v[i][j] = cd_sign(64, i xor j, j) v[i xor j] has an exact
inverse; with d the least common denominator of that inverse and N = d L_v^-1,
the integer identity N L_v = d I holds.

proofs/StiefelWitnessInvertible.v carries v, d and N as data, recomputes L_v
from v with open_gororoba's cd_sign_fuel (verified/C1474_FuelAdequacy.v, copied
from a pinned GOROROBA_ROOT by docs/evidence/stiefel_witness/replay_rocq.sh),
and checks N L_v = d I and the Stiefel conditions by vm_compute. N determines
L_v as d N^-1, so the identity can only pass when cd_sign_fuel reproduces
cd_core on this matrix. Generic sum lemmas then turn the identity into a
trivial integer kernel.

--write regenerates the proof file, --check compares it with a fresh render
and re-verifies the identity in Python, and --package-cross-check recomputes
L_v with python-hypercomplex (cayley_dickson_algebra(6, Fraction)) and writes
the comparison to docs/evidence/stiefel_witness/package_cross_check.json.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "gororoba_quantum"))

from cd_core import cd_sign  # noqa: E402

WITNESS = ROOT / "docs/evidence/moreno_stiefel/nullity.json"
PROOF = ROOT / "proofs/StiefelWitnessInvertible.v"
CROSS_CHECK = ROOT / "docs/evidence/stiefel_witness/package_cross_check.json"
DIM = 64
HALF = 32
NORM_SQUARED = 62


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def witness() -> list[int]:
    v = json.loads(WITNESS.read_text())["a6_integer_witness"]["v"]
    require(len(v) == DIM and all(isinstance(value, int) for value in v), "the witness is an integer 64-vector")
    a, b = v[:HALF], v[HALF:]
    require(a[0] == 0 and b[0] == 0, "both halves of the witness are pure")
    require(sum(x * y for x, y in zip(a, b, strict=True)) == 0, "the halves are orthogonal")
    require(sum(x * x for x in a) == NORM_SQUARED == sum(x * x for x in b), "both halves have squared norm 62")
    return v


def left_multiplication(v: list[int]) -> list[list[int]]:
    return [[cd_sign(DIM, i ^ j, j) * v[i ^ j] for j in range(DIM)] for i in range(DIM)]


def integer_left_inverse(matrix: list[list[int]]) -> tuple[int, list[list[int]]]:
    """d and N = d M^-1 with d the least common denominator of the exact inverse."""
    size = len(matrix)
    rows = [
        [Fraction(value) for value in row] + [Fraction(int(i == k)) for k in range(size)]
        for i, row in enumerate(matrix)
    ]
    for column in range(size):
        pivot = next((row for row in range(column, size) if rows[row][column] != 0), None)
        require(pivot is not None, "the left multiplication is singular")
        if pivot is None:
            raise AssertionError
        rows[column], rows[pivot] = rows[pivot], rows[column]
        lead = rows[column][column]
        rows[column] = [value / lead for value in rows[column]]
        for row in range(size):
            factor = rows[row][column]
            if row != column and factor != 0:
                rows[row] = [x - factor * y for x, y in zip(rows[row], rows[column], strict=True)]
    inverse = [augmented[size:] for augmented in rows]
    d = 1
    for inverse_row in inverse:
        for value in inverse_row:
            d = d * value.denominator // math.gcd(d, value.denominator)
    left = [[int(value * d) for value in inverse_row] for inverse_row in inverse]
    for i in range(size):
        for j in range(size):
            total = sum(left[i][k] * matrix[k][j] for k in range(size))
            require(total == (d if i == j else 0), f"N L_v differs from d I at ({i}, {j})")
    return d, left


def _z(value: int) -> str:
    return f"({value})" if value < 0 else str(value)


def _list(values: list[int]) -> str:
    return "[" + "; ".join(_z(value) for value in values) + "]"


PREAMBLE = r"""(** * The A_6 Stiefel witness of math/0512517 is not a zero divisor.

    Generated by scripts/stiefel_witness_certificate.py from the
    a6_integer_witness of docs/evidence/moreno_stiefel/nullity.json; run the
    generator with --check to bind this file to cd_core.

    v is an integer vector of length 64 in the cd_core doubling convention:
    its halves a (indices 0-31) and b (indices 32-63) are pure elements of
    A_5, orthogonal, with squared norm 62. The left multiplication
    L_v i j = sigma(i xor j, j) v (i xor j) takes sigma from open_gororoba's
    cd_sign_fuel (C-1474), at fuel 7 for dimension 64, the fuel that
    fuel_adequate_64 proves sufficient. N L_v = d I is checked by vm_compute;
    N determines L_v as d N^-1, so the check passes only when cd_sign_fuel
    and cd_core agree on this matrix. The sum lemmas below turn the identity
    into a trivial integer kernel, so L_v is invertible over Q and over every
    field containing Q. *)

From Stdlib Require Import ZArith List Lia Bool.
From OpenGororobaVerified Require Import C1474_FuelAdequacy.
Import ListNotations.
Open Scope Z_scope.

Definition sigma (p q : nat) : Z := cd_sign_fuel 7 64 p q.

Lemma sigma_fuel_adequate : check_all_pairs 7 100 64 = true.
Proof. exact fuel_adequate_64. Qed.
"""

PROOF_BODY = r"""
Definition idx : list nat := seq 0 64.

Definition Lv (i j : nat) : Z := sigma (Nat.lxor i j) j * nth (Nat.lxor i j) v 0.

Definition Nm (i k : nat) : Z := nth k (nth i N_rows []) 0.

Definition sum (l : list nat) (f : nat -> Z) : Z := fold_right (fun k acc => f k + acc) 0 l.

Definition check_entry (i j : nat) : bool :=
  Z.eqb (sum idx (fun k => Nm i k * Lv k j)) (if Nat.eqb i j then d else 0).

(** The 4096 entries of N L_v = d I, evaluated once by the virtual machine. *)
Lemma left_inverse_check_true : forallb (fun i => forallb (fun j => check_entry i j) idx) idx = true.
Proof. vm_compute. reflexivity. Qed.

Lemma forallb_pairs :
  forall (f : nat -> nat -> bool) (l : list nat),
    forallb (fun i => forallb (fun j => f i j) l) l = true ->
    forall i j, In i l -> In j l -> f i j = true.
Proof.
  intros f l H i j Hi Hj.
  rewrite forallb_forall in H. specialize (H i Hi).
  rewrite forallb_forall in H. exact (H j Hj).
Qed.

Definition dot (x y : list Z) : Z := fold_right Z.add 0 (map (fun p => fst p * snd p) (combine x y)).

Theorem witness_is_stiefel :
  length v = 64%nat /\
  nth 0 (firstn 32 v) 0 = 0 /\ nth 0 (skipn 32 v) 0 = 0 /\
  dot (firstn 32 v) (skipn 32 v) = 0 /\
  dot (firstn 32 v) (firstn 32 v) = 62 /\ dot (skipn 32 v) (skipn 32 v) = 62.
Proof. repeat split; vm_compute; reflexivity. Qed.

Theorem Lv_left_inverse :
  forall i j, In i idx -> In j idx ->
    sum idx (fun k => Nm i k * Lv k j) = if Nat.eqb i j then d else 0.
Proof.
  intros i j Hi Hj.
  exact (proj1 (Z.eqb_eq _ _) (forallb_pairs check_entry idx left_inverse_check_true i j Hi Hj)).
Qed.

Lemma d_nonzero : d <> 0.
Proof. unfold d. discriminate. Qed.

Lemma sum_ext : forall l f g, (forall k, In k l -> f k = g k) -> sum l f = sum l g.
Proof.
  induction l as [| a l IH]; intros f g H; simpl; [reflexivity |].
  rewrite (H a (or_introl eq_refl)), (IH f g (fun k Hk => H k (or_intror Hk))). reflexivity.
Qed.

Lemma sum_add : forall l f g, sum l (fun k => f k + g k) = sum l f + sum l g.
Proof. induction l as [| a l IH]; intros f g; simpl; [reflexivity | rewrite IH; ring]. Qed.

Lemma sum_scale_left : forall l c f, sum l (fun k => c * f k) = c * sum l f.
Proof. induction l as [| a l IH]; intros c f; simpl; [ring | rewrite IH; ring]. Qed.

Lemma sum_scale_right : forall l c f, sum l (fun k => f k * c) = sum l f * c.
Proof. induction l as [| a l IH]; intros c f; simpl; [ring | rewrite IH; ring]. Qed.

Lemma sum_zero : forall l, sum l (fun _ => 0) = 0.
Proof. induction l as [| a l IH]; simpl; [reflexivity | rewrite IH; reflexivity]. Qed.

Lemma sum_swap :
  forall l1 l2 (f : nat -> nat -> Z),
    sum l1 (fun i => sum l2 (fun j => f i j)) = sum l2 (fun j => sum l1 (fun i => f i j)).
Proof.
  induction l1 as [| a l1 IH]; intros l2 f; simpl.
  - symmetry. apply sum_zero.
  - rewrite IH.
    exact (eq_sym (sum_add l2 (fun j => f a j) (fun j => sum l1 (fun i => f i j)))).
Qed.

Lemma sum_delta_absent :
  forall l i c (x : nat -> Z), ~ In i l -> sum l (fun j => (if Nat.eqb i j then c else 0) * x j) = 0.
Proof.
  induction l as [| a l IH]; intros i c x H; simpl; [reflexivity |].
  destruct (Nat.eqb_spec i a) as [E | E].
  - exfalso. apply H. left. symmetry. exact E.
  - rewrite IH; [ring | intro Hin; apply H; right; exact Hin].
Qed.

Lemma sum_delta :
  forall l i c (x : nat -> Z), NoDup l -> In i l ->
    sum l (fun j => (if Nat.eqb i j then c else 0) * x j) = c * x i.
Proof.
  induction l as [| a l IH]; intros i c x Hnd Hin; [destruct Hin |].
  inversion Hnd as [| a' l' Hnotin Hnd']; subst. simpl.
  destruct (Nat.eqb_spec i a) as [E | E].
  - subst. rewrite sum_delta_absent by exact Hnotin. ring.
  - destruct Hin as [Ha | Hl]; [exfalso; apply E; symmetry; exact Ha |].
    rewrite IH by assumption. ring.
Qed.

(** L_v has no nonzero integer kernel vector: d x_t = (N L_v x)_t = 0. *)
Theorem Lv_integer_kernel_trivial :
  forall x : nat -> Z,
    (forall i, In i idx -> sum idx (fun j => Lv i j * x j) = 0) ->
    forall t, In t idx -> x t = 0.
Proof.
  intros x Hker t Ht.
  assert (Hdelta : sum idx (fun j => (if Nat.eqb t j then d else 0) * x j) = d * x t)
    by (apply sum_delta; [apply seq_NoDup | exact Ht]).
  assert (Hleft :
    sum idx (fun j => (if Nat.eqb t j then d else 0) * x j) =
    sum idx (fun k => Nm t k * sum idx (fun j => Lv k j * x j))).
  { transitivity (sum idx (fun j => sum idx (fun k => Nm t k * Lv k j) * x j)).
    - apply sum_ext. intros j Hj. cbv beta. rewrite Lv_left_inverse by assumption. reflexivity.
    - transitivity (sum idx (fun j => sum idx (fun k => Nm t k * Lv k j * x j))).
      + apply sum_ext. intros j _. cbv beta.
        exact (eq_sym (sum_scale_right idx (x j) (fun k => Nm t k * Lv k j))).
      + transitivity (sum idx (fun k => sum idx (fun j => Nm t k * Lv k j * x j))).
        * exact (sum_swap idx idx (fun j k => Nm t k * Lv k j * x j)).
        * apply sum_ext. intros k _. cbv beta.
          transitivity (sum idx (fun j => Nm t k * (Lv k j * x j))).
          -- apply sum_ext. intros j _. cbv beta. ring.
          -- exact (sum_scale_left idx (Nm t k) (fun j => Lv k j * x j)). }
  assert (Hzero : sum idx (fun k => Nm t k * sum idx (fun j => Lv k j * x j)) = 0).
  { transitivity (sum idx (fun _ => 0)); [| apply sum_zero].
    apply sum_ext. intros k Hk. cbv beta. rewrite Hker by exact Hk. apply Z.mul_0_r. }
  assert (Hprod : d * x t = 0) by (rewrite <- Hdelta, Hleft; exact Hzero).
  apply Z.mul_eq_0 in Hprod. destruct Hprod as [Hd | Hx]; [exfalso; exact (d_nonzero Hd) | exact Hx].
Qed.
"""


def render(v: list[int], d: int, left: list[list[int]]) -> str:
    rows = ";\n  ".join(_list(row) for row in left)
    data = (
        f"\nDefinition v : list Z :=\n  {_list(v)}.\n\n"
        f"Definition d : Z := {d}.\n\n"
        f"Definition N_rows : list (list Z) := [\n  {rows}].\n"
    )
    return PREAMBLE + data + PROOF_BODY


def certificate_text() -> str:
    v = witness()
    d, left = integer_left_inverse(left_multiplication(v))
    return render(v, d, left)


def package_cross_check() -> dict[str, object]:
    """L_v from python-hypercomplex, an implementation independent of cd_core, against cd_core."""
    from importlib.metadata import version

    import hypercomplex

    v = witness()
    algebra = hypercomplex.cayley_dickson_algebra(6, Fraction)
    element = algebra(*[Fraction(value) for value in v])
    matrix = left_multiplication(v)
    mismatches = 0
    for j in range(DIM):
        column = (element * algebra.e(j)).coefficients()
        mismatches += sum(1 for i in range(DIM) if Fraction(column[i]) != matrix[i][j])
    return {
        "schema": "stiefel-witness-package-cross-check-v1",
        "package": "hypercomplex",
        "version": version("hypercomplex"),
        "construction": "cayley_dickson_algebra(6, fractions.Fraction); column j of L_v is v * e(j)",
        "columns_compared": DIM,
        "mismatched_entries": mismatches,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--package-cross-check", action="store_true")
    arguments = parser.parse_args()
    try:
        if arguments.package_cross_check:
            result = package_cross_check()
            require(result["mismatched_entries"] == 0, "python-hypercomplex disagrees with cd_core on L_v")
            CROSS_CHECK.parent.mkdir(parents=True, exist_ok=True)
            CROSS_CHECK.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
            return 0
        text = certificate_text()
        if arguments.write:
            PROOF.write_text(text)
            return 0
        require(PROOF.read_text() == text, f"{PROOF.relative_to(ROOT)} differs from a fresh render; run --write")
    except (ValueError, KeyError, OSError) as error:
        print(f"stiefel witness certificate: {error}", file=sys.stderr)
        return 1
    print("stiefel witness certificate: N L_v = d I, Stiefel conditions and the Rocq source agree with cd_core")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
