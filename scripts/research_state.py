def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


class IbmRuns:
    """IBM Quantum runs: the retained-run audit bound to the service inventory."""

    name = "ibm"
    title = "IBM Quantum"
    charge_unit = "s"
    source = "the retained-run audit"
    absent = "holds no audited job"

    def __init__(self) -> None:
        audit = load_json(RETENTION_AUDIT)
        service = load_json(SERVICE_INVENTORY)
        require(
            audit.get("inventory_sha256") == digest(SERVICE_INVENTORY),
            "the retention audit binds a different service inventory",
        )
        self.jobs: list[dict[str, Any]] = audit["jobs"]
        self.service = service
        self.status = {job["job_id"]: job["status"] for job in service["jobs"]}

    def runs(self) -> dict[str, dict[str, Any]]:
        grouped: dict[str, list[dict[str, Any]]] = {}
        for job in self.jobs:
            grouped.setdefault(job["run"], []).append(job)
        facts = {}
        for run, jobs in grouped.items():
            jobs = sorted(jobs, key=lambda job: job["created_at"])
            for job in jobs:
                require(job["job_id"] in self.status, f"audited job {job['job_id']} is absent from the inventory")
            facts[run] = {
                "created_at": jobs[0]["created_at"],
                "backends": sorted({job["backend"] for job in jobs}),
                "jobs": len(jobs),
                "circuits": sum(job["pub_count"] for job in jobs),
                "statuses": Counter(self.status[job["job_id"]] for job in jobs),
                "charge": sum(job["final_qpu_charge_seconds"] for job in jobs),
                "detail": "",
            }
        return facts

    def account_line(self) -> str:
        usage = self.service["account_usage"]
        charge = sum(job["final_qpu_charge_seconds"] for job in self.jobs)
        return (
            f"The IBM service inventory observed at {self.service['observed_at']} holds {len(self.jobs)} physical "
            f"jobs with {charge} settled seconds; the account then reported {usage['usage_consumed_seconds']} of "
            f"{usage['usage_limit_seconds']} s consumed in the rolling window ending "
            f"{usage['usage_period']['end_time']}. That is an observation, not a current balance or an authorization."
        )


def _optional_json(path: Path) -> Any:
    return load_json(path) if path.is_file() else None


class QuantumInspireRuns:
    """Quantum Inspire runs: the retained run directories bound to the account ledger.

    Loading reads the files; runs() applies every rule to the loaded copy, so
    the self-test reaches each rule by mutating that copy.
    """

    name = "quantum_inspire"
    title = "Quantum Inspire"
    charge_unit = "ledger change"
    source = "the Quantum Inspire run directories"
    absent = "is not a retained Quantum Inspire run"

    def __init__(self) -> None:
        self.ledger: dict[str, Any] = load_json(QI_LEDGER)
        self.records: dict[str, dict[str, Any]] = {}
        for submission in sorted(QI_RUNS.glob("*/submission.json")):
            directory = submission.parent
            cases = _optional_json(directory / "cases.json")
            circuits = {}
            for row in (cases or {}).get("circuits", []):
                path = directory / row["file"]
                circuits[row["file"]] = digest(path) if path.is_file() else None
            raw_dir = directory / "raw"
            raw = {path.name: load_json(path) for path in sorted(raw_dir.iterdir())} if raw_dir.is_dir() else {}
            self.records[directory.relative_to(ROOT).as_posix()] = {
                "submission": load_json(submission),
                "cases": cases,
                "results": _optional_json(directory / "results.json"),
                "circuits": circuits,
                "raw": raw,
            }

    def _run(self, run: str, record: dict[str, Any]) -> tuple[dict[str, Any], dict[int, tuple[Any, ...]]]:
        owner = f"Quantum Inspire run {run}"
        submission = record["submission"]
        require(submission.get("schema") == "qi-submission-v1", f"{owner}: submission.json schema differs")
        require(
            isinstance(submission.get("approval"), str) and submission["approval"],
            f"{owner}: submission.json records no approval",
        )
        cases = record["cases"]
        require(isinstance(cases, dict), f"{owner}: cases.json is missing")
        for field, key in (("backend", "backend"), ("backend_type_id", "backend_type_id"), ("shots", "shots")):
            require(cases.get(key) == submission[field], f"{owner}: cases.json and submission.json differ in {field}")
        files = [row["file"] for row in submission["jobs"]]
        require(files == [row["file"] for row in cases["circuits"]], f"{owner}: submitted files differ from cases.json")
        for row in cases["circuits"]:
            require(
                record["circuits"].get(row["file"]) == row["sha256"],
                f"{owner}: circuit {row['file']} digest differs from cases.json",
            )
        collected = record["results"]
        require(isinstance(collected, dict), f"{owner}: results.json is missing; collect the run")
        require(collected.get("schema") == "qi-collection-v1", f"{owner}: results.json schema differs")
        require(
            [(row["file"], row["job"]["id"]) for row in collected["jobs"]]
            == [(row["file"], row["job"]) for row in submission["jobs"]],
            f"{owner}: results.json jobs differ from submission.json",
        )
        job_ids = {row["job"] for row in submission["jobs"]}
        charges: Counter[int] = Counter()
        for transaction in collected["transactions"]:
            require(transaction["job"] in job_ids, f"{owner}: transaction {transaction['id']} charges another job")
            charges[transaction["job"]] += transaction["change"]
        completed: dict[str, dict[str, Any]] = {}
        jobs: dict[int, tuple[Any, ...]] = {}
        for row in collected["jobs"]:
            job = row["job"]
            require(
                job["batch_job_id"] == submission["batch_job"] and job["number_of_shots"] == submission["shots"],
                f"{owner}: job {job['id']} names another batch job or shot count",
            )
            if job["status"] == "completed":
                results = row["results"]
                require(
                    len(results) == 1
                    and results[0]["job_id"] == job["id"]
                    and results[0]["shots_requested"] == submission["shots"],
                    f"{owner}: completed job {job['id']} holds one result of the submitted shots",
                )
                completed[f"{row['file']}.json"] = results[0]
            else:
                require(not row["results"], f"{owner}: {job['status']} job {job['id']} holds results")
            done = sum(result["shots_done"] for result in row["results"])
            jobs[job["id"]] = (
                submission["backend_type_id"],
                submission["batch_job"],
                job["status"],
                done,
                charges[job["id"]],
            )
        require(
            set(record["raw"]) == set(completed),
            f"{owner}: raw/ holds {sorted(record['raw'])}, the completed jobs need {sorted(completed)}",
        )
        for name, result in completed.items():
            shots = record["raw"][name]
            require(
                isinstance(shots, list) and len(shots) == result["shots_done"],
                f"{owner}: raw/{name} length differs from the {result['shots_done']} shots done",
            )
            require(
                Counter(shots) == Counter(result["results"]),
                f"{owner}: raw/{name} differs from the recorded outcome histogram",
            )
        created = min(row["job"]["created_on"] for row in collected["jobs"])
        shots_done = sum(job[3] for job in jobs.values())
        requested = len(jobs) * submission["shots"]
        facts = {
            "created_at": created,
            "backends": [submission["backend"]],
            "jobs": len(jobs),
            "circuits": len(jobs),
            "statuses": Counter(job[2] for job in jobs.values()),
            "charge": sum(charges.values()),
            "detail": f"batch job {submission['batch_job']}, {shots_done} of {requested} shots done",
        }
        return facts, jobs

    def runs(self) -> dict[str, dict[str, Any]]:
        require(self.ledger.get("schema") == "qi-usage-v1", "the Quantum Inspire ledger schema differs")
        facts = {}
        retained: dict[int, tuple[Any, ...]] = {}
        for run, record in self.records.items():
            facts[run], jobs = self._run(run, record)
            retained.update(jobs)
        ledger = {
            job["job"]: (job["backend_type_id"], job["batch_job"], job["status"], job["shots_done"], job["charged"])
            for job in self.ledger["jobs"]
        }
        require(
            ledger == retained,
            "the Quantum Inspire ledger and the retained run directories record different jobs "
            f"(ledger only {sorted(set(ledger) - set(retained))}, runs only {sorted(set(retained) - set(ledger))}, "
            f"differing {sorted(job for job in set(ledger) & set(retained) if ledger[job] != retained[job])})",
        )
        return facts

    def account_line(self) -> str:
        totals = self.ledger["totals"]
        return (
            f"The Quantum Inspire ledger retrieved at {self.ledger['retrieved_utc']} lists {len(self.ledger['jobs'])} "
            f"jobs with {totals['shots_done']} shots done and a total ledger change of {totals['change']}, and every "
            "listed job belongs to a retained run directory. That is an observation, not a quota or an authorization."
        )


