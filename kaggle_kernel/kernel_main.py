"""Kernel-side program of scripts/kaggle_run.py, run from the unpacked repository root on Kaggle.

The bootstrap run.py installs KERNEL_PINS, unpacks the bundle into
/kaggle/working/repo and runs this file with the job description in
kernel_job.json. Every kernel then executes the same phases, each writing
one JSON file into /kaggle/working/output:

1. ``environment.json``: the measured substrate. Python and package
   versions, CPU model and logical cores, RAM, working-disk capacity, every
   GPU (name, memory, driver, CUDA, compute capability), the Aer devices,
   and the Kaggle input models attached to the kernel.
2. ``hypercomplex.json``: the repository's hypercomplex stack, built and
   proved. scripts/algebra_package_tables.py fetches every pinned archive
   (sha256-checked), installs it through the PKGBUILD recipes, and
   regenerates docs/evidence/algebra_packages/tables.json; the kernel stops
   before the experiment unless the regenerated bytes equal the bundled ones.
3. ``capacity.json`` (smoke kernels only): the largest density-matrix and
   statevector GHZ circuits that run on the GPU, each width tried once in
   its own process and the file rewritten after every trial.
4. The entry: its stdout and stderr, its exit code, and every file it
   created or changed under the repository root, copied to output/repo/.

kaggle_kernel/AGENTS.md is printed into the kernel log so the instructions
travel with every run.
"""

from __future__ import annotations

import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import time
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parent.parent
OUT = Path("/kaggle/working/output")
ARCHIVES = Path("/tmp/gororoba/archives")
TABLES = REPO / "docs/evidence/algebra_packages/tables.json"
REPORTED_PACKAGES = (
    "qiskit",
    "qiskit-aer-gpu-cu11",
    "numpy",
    "scipy",
    "sympy",
    "pandas",
    "torch",
    "numpy-quaternion",
    "hypercomplex",
    "hypercomplex-engine",
    "hypercomplex-algebra",
    "Cayley-Calculator",
    "cayley-dickson",
    "octonion",
    "SplitOct",
    "mathdunders",
)
DM_WIDTHS = (12, 13, 14, 15)
SV_WIDTHS = (26, 28, 29, 30, 31)
TRIAL_TIMEOUT = 600


def write(name: str, data: Any) -> None:
    (OUT / name).write_text(json.dumps(data, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(f"{name}: {json.dumps(data, sort_keys=True)[:3000]}", flush=True)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(*cmd: str) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(list(cmd), capture_output=True, text=True, cwd=REPO)
    except FileNotFoundError as error:
        return subprocess.CompletedProcess(list(cmd), 127, "", str(error))


def versions() -> dict[str, str | None]:
    found: dict[str, str | None] = {}
    for name in REPORTED_PACKAGES:
        try:
            found[name] = version(name)
        except PackageNotFoundError:
            found[name] = None
    return found


def meminfo_gib(field: str) -> float | None:
    for line in Path("/proc/meminfo").read_text().splitlines():
        if line.startswith(field + ":"):
            return round(int(line.split()[1]) / 2**20, 2)
    return None


def cpu_model() -> str | None:
    for line in Path("/proc/cpuinfo").read_text().splitlines():
        if line.startswith("model name"):
            return line.split(":", 1)[1].strip()
    return None


def gpus() -> list[dict[str, Any]]:
    query = "name,memory.total,driver_version,compute_cap"
    proc = run("nvidia-smi", f"--query-gpu={query}", "--format=csv,noheader,nounits")
    rows = []
    for line in proc.stdout.strip().splitlines():
        name, memory, driver, capability = (field.strip() for field in line.split(","))
        rows.append({"name": name, "memory_mib": int(memory), "driver": driver, "compute_capability": capability})
    return rows


def cuda_version() -> str | None:
    for line in run("nvidia-smi").stdout.splitlines():
        if "CUDA Version" in line:
            return line.split("CUDA Version:")[1].split()[0]
    return None


def tpus() -> dict[str, Any]:
    """JAX's TPU devices, the only TPU access a kernel has; Aer has no TPU backend."""
    try:
        import jax

        return {"jax": jax.__version__, "devices": [str(device) for device in jax.devices("tpu")]}
    except Exception as error:  # no jax, or no TPU attached
        return {"devices": [], "error": f"{type(error).__name__}: {str(error)[:200]}"}


def attached_models() -> list[str]:
    root = Path("/kaggle/input")
    if not root.is_dir():
        return []
    return sorted(str(p.parent.relative_to(root)) for p in root.rglob("config.json"))


def environment() -> dict[str, Any]:
    import qiskit_aer

    disk = shutil.disk_usage("/kaggle/working")
    return {
        "python": platform.python_version(),
        "platform": platform.platform(),
        "cpu_model": cpu_model(),
        "logical_cpus": os.cpu_count(),
        "affinity_cpus": len(os.sched_getaffinity(0)),
        "ram_total_gib": meminfo_gib("MemTotal"),
        "ram_available_gib": meminfo_gib("MemAvailable"),
        "working_disk_total_gib": round(disk.total / 2**30, 2),
        "working_disk_free_gib": round(disk.free / 2**30, 2),
        "gpus": gpus(),
        "cuda_driver_version": cuda_version(),
        "tpus": tpus(),
        "aer_devices": list(qiskit_aer.AerSimulator().available_devices()),
        "attached_models": attached_models(),
        "packages": versions(),
    }


def hypercomplex() -> dict[str, Any]:
    retained = sha256(TABLES)
    script = "scripts/algebra_package_tables.py"
    steps = {}
    for mode in ("--fetch", "--install", "--extract"):
        proc = run(sys.executable, "-B", script, mode, str(ARCHIVES))
        steps[mode] = {"returncode": proc.returncode, "tail": (proc.stdout + proc.stderr)[-1500:]}
        if proc.returncode:
            break
    regenerated = sha256(TABLES)
    return {
        "tables_retained_sha256": retained,
        "tables_regenerated_sha256": regenerated,
        "identical": retained == regenerated and all(step["returncode"] == 0 for step in steps.values()),
        "steps": steps,
        "packages": versions(),
    }


def ghz_trial(method: str, width: int, device: str = "GPU") -> dict[str, Any]:
    from qiskit import QuantumCircuit, transpile
    from qiskit_aer import AerSimulator

    circuit = QuantumCircuit(width)
    circuit.h(0)
    for q in range(width - 1):
        circuit.cx(q, q + 1)
    circuit.measure_all()
    simulator = AerSimulator(method=method, device=device)
    start = time.time()
    try:
        counts = simulator.run(transpile(circuit, simulator), shots=256, seed_simulator=7).result().get_counts()
    except Exception as error:  # Aer reports insufficient GPU memory as a runtime error
        return {"width": width, "ok": False, "error": f"{type(error).__name__}: {str(error)[:300]}"}
    ok = set(counts) == {"0" * width, "1" * width}
    return {"width": width, "ok": ok, "wall_seconds": round(time.time() - start, 3)}


def capacity() -> dict[str, Any]:
    """Each width runs in its own process, so an allocation the host kills ends that trial only."""
    if not gpus():
        skipped = {"skipped": "no GPU attached"}
        write("capacity.json", skipped)
        return skipped
    result: dict[str, Any] = {
        "shots": 256,
        "circuit": "GHZ: H then a CX chain, measured on every qubit",
        "trial_timeout_seconds": TRIAL_TIMEOUT,
        "density_matrix": [],
        "statevector": [],
    }
    for method, widths in (("density_matrix", DM_WIDTHS), ("statevector", SV_WIDTHS)):
        for width in widths:
            cmd = [sys.executable, "-B", str(Path(__file__).resolve()), "--trial", method, str(width)]
            try:
                proc = subprocess.run(cmd, capture_output=True, text=True, timeout=TRIAL_TIMEOUT)
            except subprocess.TimeoutExpired:
                trial = {"width": width, "ok": False, "error": f"timeout after {TRIAL_TIMEOUT} s"}
            else:
                lines = proc.stdout.strip().splitlines()
                if proc.returncode == 0 and lines:
                    trial = json.loads(lines[-1])
                else:
                    tail = (proc.stdout + proc.stderr)[-300:]
                    trial = {"width": width, "ok": False, "error": f"exit {proc.returncode}: {tail}"}
            result[method].append(trial)
            write("capacity.json", result)
    return result


def unpack_datasets(datasets: list[dict[str, Any]]) -> dict[str, Any]:
    """Extract each attached dataset archive into the repository root and verify every file's sha256."""
    import tarfile

    report: dict[str, Any] = {}
    for entry in datasets:
        slug = entry["ref"].split("/")[1]
        candidates = [p for p in Path("/kaggle/input").rglob(entry["archive"]) if slug in p.parts]
        if len(candidates) != 1:
            raise SystemExit(f"dataset {entry['ref']}: {len(candidates)} archives named {entry['archive']}")
        with tarfile.open(candidates[0]) as archive:
            archive.extractall(REPO, filter="data")
        mismatched = [rel for rel, digest in entry["files"].items() if sha256(REPO / rel) != digest]
        report[entry["ref"]] = {"archive": str(candidates[0]), "files": len(entry["files"]), "mismatched": mismatched}
        if mismatched:
            raise SystemExit(f"dataset {entry['ref']}: {len(mismatched)} files differ from the manifest")
    return report


def main() -> int:
    if len(sys.argv) in (4, 5) and sys.argv[1] == "--trial":
        device = sys.argv[4] if len(sys.argv) == 5 else "GPU"
        print(json.dumps(ghz_trial(sys.argv[2], int(sys.argv[3]), device)), flush=True)
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    # exit.json marks a finished run on every path; scripts/kaggle_run.py
    # collect requires it, because `kernels status` reports the slug's latest
    # version whatever version it names.
    code = 1
    try:
        code = run_entry()
    finally:
        write("exit.json", {"returncode": code})
    return code


def run_entry() -> int:
    job = json.loads((REPO / "kaggle_kernel/kernel_job.json").read_text(encoding="utf-8"))
    print((REPO / "kaggle_kernel/AGENTS.md").read_text(encoding="utf-8"), flush=True)
    if job.get("datasets"):
        write("datasets.json", unpack_datasets(job["datasets"]))
    before = {p: sha256(p) for p in REPO.rglob("*") if p.is_file()}
    write("environment.json", environment())
    stack = hypercomplex()
    write("hypercomplex.json", stack)
    if not stack["identical"]:
        print("hypercomplex stack differs from the repository's retained tables; the entry does not run", flush=True)
        return 3
    if job["smoke"]:
        capacity()
        return 0
    env = dict(os.environ, GOROROBA_AER_DEVICE=job.get("device", "GPU"), PYTHON=sys.executable)
    proc = subprocess.run(
        [sys.executable, "-B", job["entry"], *job["args"]], cwd=REPO, env=env, capture_output=True, text=True
    )
    (OUT / "stdout.txt").write_text(proc.stdout, encoding="utf-8")
    (OUT / "stderr.txt").write_text(proc.stderr, encoding="utf-8")
    print(proc.stdout[-4000:], proc.stderr[-4000:], sep="\n", flush=True)
    for path in REPO.rglob("*"):
        if path.is_file() and path != TABLES and before.get(path) != sha256(path):
            target = OUT / "repo" / path.relative_to(REPO)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(path.read_bytes())
    return proc.returncode


if __name__ == "__main__":
    raise SystemExit(main())
